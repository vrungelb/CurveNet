function cfg = cnConfig()
%CNCONFIG  Все константы и пути проекта CurveNet в одном месте.
%
%   cfg = CNCONFIG()
%
%   Ни один другой файл проекта не должен содержать «магических чисел».
%   Если понадобилось подкрутить размер картинки, силу дрожания руки или
%   объём датасета — правка делается здесь и только здесь.
%
%   Значение кэшируется в persistent-переменной, поэтому вызывать функцию
%   можно свободно, в том числе внутри циклов. Чтобы подхватить правки
%   этого файла без перезапуска MATLAB, выполните:
%
%       clear cnConfig
%
%   Разделы
%   -------
%   paths     пути к папкам проекта
%   img       растровое представление кривой
%   curve     дискретизация кривой точками
%   data      объём датасета и его разбиение
%   aug       имитация рисования от руки
%   input     проверки живого ввода с холста
%   train     обучение классификатора
%   regress   обучение регрессоров
%   refine    уточняющая нелинейная подгонка
%
%   См. также CNCLASSES.

persistent CFG
if ~isempty(CFG)
    cfg = CFG;
    return
end

% =======================================================================
%  Пути
% =======================================================================
% Корень определяется по расположению самого файла, а не жёстко прописан:
% проект можно переносить и переименовывать без правок.
here = fileparts(mfilename("fullpath"));    % .../CurveNet/config
root = fileparts(here);                      % .../CurveNet

cfg.paths.root     = root;
cfg.paths.dataset  = fullfile(root, "dataset");
cfg.paths.images   = fullfile(root, "dataset", "images");   % подпапка на класс
cfg.paths.meta     = fullfile(root, "dataset", "meta.mat"); % таблица параметров
cfg.paths.split    = fullfile(root, "dataset", "split.mat");% индексы разбиения
cfg.paths.models   = fullfile(root, "models");
cfg.paths.results  = fullfile(root, "results");
cfg.paths.userTest = fullfile(root, "userTest");            % рисунки своей рукой

% =======================================================================
%  Растр
% =======================================================================
cfg.img.size = 160;         % сторона квадратной картинки в пикселях

% Поле по краям кадра. Нужно по двум причинам: линия конечной толщины не
% должна упираться в границу, и небольшой запас делает сеть устойчивее к
% неточностям нормализации на живом вводе.
cfg.img.pad = 0.08;         % доля стороны кадра с каждой стороны

% Толщина линии в пикселях. Разброс имитирует разные кисти и разный размер
% исходного рисунка: мелко нарисованная кривая после вписывания в кадр даёт
% относительно более толстую линию.
cfg.img.lineWidth = [1.6 3.2];

% Сглаживание краёв линии. Холст рисует с антиалиасингом, и синтетика должна
% выглядеть так же, иначе сеть научится различать «идеально резкий» и
% «размытый» край и провалится на живом вводе.
cfg.img.softenSigma = [0.4 0.9];

% Формат хранения. PNG выбран потому, что картинки почти бинарные и жмутся
% в единицы килобайт; тот же датасет в одном .mat занял бы гигабайты.
cfg.img.format = "png";

% Шаг, с которым точки штриха уплотняются перед растеризацией, в пикселях.
% Должен быть заметно меньше единицы, иначе линия распадётся на отдельные
% точки на участках с большой кривизной.
cfg.img.splatStep = 0.4;

% Линия белая на чёрном фоне, а не наоборот. Так фон равен нулю, и это
% совпадает с тем, чем свёрточные слои дополняют края при паддинге: сеть не
% видит на границе кадра ложной «линии».
cfg.img.lineOnBlack = true;

% =======================================================================
%  Дискретизация кривой
% =======================================================================
% Человек ведёт руку с конечной скоростью, и точек в штрихе получается
% немного. Строить кривую по десяткам тысяч точек неправильно вдвойне: это
% не похоже на реальный ввод и на порядок медленнее.
cfg.curve.nPoints = [150 320];

% Точки распределяются равномерно по длине дуги, а не по параметру. Иначе у
% спиралей и роз плотность точек резко скачет, и растр выходит рваным.
cfg.curve.arcLengthResample = true;

% Разброс плотности точек: у мелко нарисованной кривой их объективно меньше.
cfg.curve.densityJitter = [0.7 1.3];

% =======================================================================
%  Датасет
% =======================================================================
cfg.data.perClass = 7000;                 % примеров на каждый класс
cfg.data.split    = [0.70 0.15 0.15];     % обучение / валидация / тест
cfg.data.seed     = 20260818;             % для воспроизводимости

% Разбиение выполняется по классам отдельно, чтобы в каждой из трёх частей
% все классы были представлены в одинаковой пропорции.
cfg.data.stratified = true;

% Каждой картинке при генерации выдаётся собственный seed, записываемый в
% таблицу метаданных. По нему любой пример восстанавливается точь-в-точь —
% это незаменимо, когда разбираешься, почему сеть ошиблась именно на нём.
cfg.data.storeSeeds = true;

% =======================================================================
%  Имитация руки
% =======================================================================
% Три уровня искажения, каждый отвечает за своё. Все амплитуды заданы в
% долях размера кривой и домножаются на множитель distort из cnClasses:
% розе, астроиде и лемнискате сильная деформация противопоказана.

% Уровень 1: крупная упругая деформация — форма плывёт целиком.
cfg.aug.warpAmp   = [0.02 0.07];   % амплитуда
cfg.aug.warpScale = 7;             % длина сглаживания как доля числа точек

% Доля деформации, общая для всех штрихов фигуры. Человек ведёт обе ветви
% гиперболы одной рукой, и их перекос согласован; при полностью независимой
% деформации ветви выглядят как две несвязанные линии. Оставшаяся доля
% разыгрывается для каждого штриха отдельно — идеальным зеркалом друг друга
% они тоже не бывают.
cfg.aug.warpShare = 0.65;

% Радиальное гуляние: рука не держит постоянного расстояния от центра
% фигуры. Радиус плавно уходит то наружу, то внутрь, и множитель здесь
% именно множитель, а не сдвиг — отклонение растёт вместе с радиусом, как
% оно и бывает у человека.
%
% Для спиралей это ключевой вид искажения: он заставляет шаг витков гулять.
% Без него все архимедовы спирали в датасете имеют идеально постоянный шаг,
% которого от руки не бывает, и любая живая спираль с расходящимися витками
% уходит в логарифмические.
cfg.aug.radialAmp = [0 0.055];

% Уровень 2: тремор — мелкое дрожание. Шум обязательно сглаженный: тремор
% руки коррелирован во времени, а белый шум даёт не дрожащую линию, а ёжика.
cfg.aug.tremorAmp   = [0.006 0.020];
cfg.aug.tremorSigma = 2.5;         % сглаживание вдоль линии, в точках

% Уровень 3: артефакты рисования.
cfg.aug.openProb   = 0.60;         % вероятность незамкнутого контура
cfg.aug.openGap    = [0.01 0.05];  % размер незамыкания, доля длины
cfg.aug.breakProb  = 0.22;         % вероятность отрыва пера
cfg.aug.breakCount = [1 2];        % сколько отрывов
cfg.aug.breakLen   = [0.02 0.06];  % длина отрыва, доля длины

% Рвать линию вплотную к её концу бессмысленно: это неотличимо от того, что
% человек просто не довёл её до конца, а такой случай уже описан openGap.
cfg.aug.breakMargin = 0.08;        % доля длины штриха у каждого конца

% Огрызки, оставшиеся между отрывами, короче этого порога выбрасываются: на
% картинке они превращаются в точку или короткую чёрточку, то есть в шум,
% который сеть может принять за часть формы.
cfg.aug.minFragment = 0.03;        % доля длины исходного штриха

% Геометрия. Поворот на полный круг — обязательное требование: кривая должна
% узнаваться под любым углом.
cfg.aug.rotation = [0 360];        % градусы

% Анизотропия моделирует «эффект угла»: рисуя у края холста, человек
% подсознательно поджимает фигуру, и она выходит сплющенной по одной оси.
% Само положение на холсте моделировать не нужно — его снимает нормализация.
%
% Значение общее и переопределяется полем aniso в cnClasses там, где
% растяжение меняет не вид кривой, а её параметр. У окружности и эллипса
% оно перетаскивало бы примеры через границу между классами и портило
% разметку, поэтому там заданы свои, узкие диапазоны.
cfg.aug.aniso = [0.85 1.15];
cfg.aug.shear = [-0.12 0.12];

% Остаточный разброс после нормализации. Идеально вписанные данные делают
% сеть хрупкой: она привыкает, что кривая всегда точно в кадре, и удивляется
% малейшему отклонению на живом вводе.
cfg.aug.scaleJitter  = [0.92 1.08];
cfg.aug.offsetJitter = 0.03;       % доля стороны кадра

% =======================================================================
%  Проверки живого ввода
% =======================================================================
% Вырожденный ввод — точка, микрочёрточка, почти прямая линия — отсекается
% правилом до сети. Информации там физически нет, и гнать это в нейронку
% незачем: правило надёжнее, мгновенно и не требует обучения.
cfg.input.minPoints     = 12;      % точек во всех штрихах суммарно
cfg.input.minBoxFrac    = 0.05;    % габаритная рамка от стороны холста
cfg.input.minStrokeFrac = 0.02;    % штрихи короче — считаем случайными и
                                    % выбрасываем до подсчёта рамки

% Одиночный клик мимо растягивает габаритную рамку вдвое, после чего сама
% кривая ужимается в четверть кадра и распознавание разваливается. Отсев
% коротких штрихов лечит именно это.
cfg.input.minStrokePoints = 5;

% Кривая, упёршаяся в границу холста, скорее всего обрезана, и параметры
% вернутся искажёнными. Не ошибка, но повод предупредить пользователя.
cfg.input.edgeTol = 0.005;         % доля стороны холста

% =======================================================================
%  Обучение классификатора
% =======================================================================
cfg.train.miniBatchSize   = 128;
cfg.train.maxEpochs       = 30;
cfg.train.initialLearnRate = 1e-3;
cfg.train.lrDropFactor    = 0.2;

% Через сколько эпох снижать темп обучения. Восемь, а не двенадцать: на
% первом прогоне валидационная точность заметно скакала — при крупном шаге
% сеть проскакивает мимо минимума и не может в нём осесть. Раннее снижение
% темпа эти скачки гасит.
cfg.train.lrDropPeriod    = 8;

cfg.train.l2Regularization = 1e-4;

% Сколько проверок валидации подряд без улучшения терпеть до остановки.
% Считается в ПРОВЕРКАХ, а не в эпохах, а проверок у нас две за эпоху —
% шесть означало всего три эпохи терпения. При скачущей валидации этого не
% хватало: обучение обрывалось на пятой эпохе из тридцати, так и не дойдя
% до снижения темпа обучения.
cfg.train.validationPatience = 12;
cfg.train.shuffle         = "every-epoch";
cfg.train.environment     = "auto";% "auto" сам возьмёт GPU, если он есть

% Где готовить данные к подаче в сеть. Обучение идёт на видеокарте, а чтение
% и раскодировку девяноста тысяч PNG на каждой эпохе по умолчанию выполняет
% один поток главного процесса MATLAB — и пока он этим занят, видеокарта
% простаивает.
%
% Значение "parallel" отдаёт эту работу отдельным процессам: у шестиядерной
% машины их будет пять, и главный поток занимается только кормлением
% видеокарты. Выигрыш обычно тридцать-пятьдесят процентов времени эпохи.
%
% Цена — полминуты-минута на подъём пула при первом запуске и лишняя
% оперативная память. Если Parallel Computing Toolbox не установлен,
% cnTrainClassifier молча возьмёт "serial".
cfg.train.preprocessing   = "parallel";
cfg.train.verboseFreq     = 50;
cfg.train.plots           = "training-progress";

% =======================================================================
%  Обучение регрессоров
% =======================================================================
% Регрессоры мельче классификатора: у них два-семь выходов и куда более
% простая задача, потому что класс уже известен.
cfg.regress.miniBatchSize    = 128;
cfg.regress.maxEpochs        = 40;
cfg.regress.initialLearnRate = 1e-3;
cfg.regress.lrDropFactor     = 0.2;
cfg.regress.lrDropPeriod     = 18;
cfg.regress.l2Regularization = 1e-4;
cfg.regress.environment      = "auto";

% Вес классификационной головы (число лепестков розы) в общей функции потерь
% относительно регрессионной части.
cfg.regress.headWeight = 0.5;

% =======================================================================
%  Уточняющая подгонка
% =======================================================================
% Нейронная регрессия даёт оценку с погрешностью в несколько процентов, и на
% глаз видно, что наложенная кривая чуть-чуть не совпадает. Нелинейный МНК
% доводит её до точного совмещения, стартуя из предсказания сети — то есть
% из заведомо правильной области, а не из случайной точки.
cfg.refine.enabledByDefault = true;   % состояние галочки в интерфейсе
cfg.refine.maxIterations    = 200;
cfg.refine.tolerance        = 1e-8;

% Невязка после подгонки — самый надёжный признак того, что класс определён
% неверно. Если человек нарисовал звезду, а классификатор ответил
% «астроида», среднее расстояние от его точек до наложенной кривой окажется
% огромным, и это видно сразу, без всякой нейронной уверенности.
cfg.refine.residualWarn   = 0.035;   % доля размера габаритной рамки
cfg.refine.residualReject = 0.080;

% Порог уверенности классификатора, ниже которого ответ считается
% ненадёжным. Работает вместе с проверкой невязки, а не вместо неё: сети
% склонны быть переуверенными на данных, которых не видели.
cfg.refine.minConfidence = 0.55;

CFG = cfg;
end
