function c = mk(key, name, varargin)
c = struct( ...
    "key", string(key), ...
    "name", string(name), ...
    "isCurve", true, ...
    "closed", true, ...
    "nStrokes", 1, ...
    "hasAngle", true, ...
    "symDeg", 360, ...
    "regAffine", true, ...
    "flipMode", "sym360", ...
    "shape", {emptyPar()}, ...
    "kValues", {[]}, ...
    "distort", 1.0, ...
    "aniso", {[]}, ...
    "shear", {[]});

if mod(numel(varargin), 2) ~= 0
    error("cnClasses:badPairs", "Правки задаются парами «имя поля», значение (класс %s).", key);
end

for i = 1:2:numel(varargin)
    f = string(varargin{i});
    if ~isfield(c, f)
        error("cnClasses:badField", "У класса %s нет поля «%s».", key, f);
    end
    c.(f) = varargin{i+1};
end
end

function b = circleEllipseBound()
