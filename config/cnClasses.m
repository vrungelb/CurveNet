function out = cnClasses(sel)
%CNCLASSES  Словарь классов проекта CurveNet.
%
%   Единственное место, где описано, какие классы существуют, как они
%   называются, какими параметрами задаются и какой симметрией обладают.
%   Все остальные модули проекта обращаются сюда и не держат своих копий
%   этих сведений.
%
%   C = CNCLASSES()          массив структур со всеми классами
%   c = CNCLASSES(i)         класс по номеру
%   c = CNCLASSES("ellipse") класс по ключу
%   T = CNCLASSES("table")   сводная таблица для просмотра глазами
%
%   Поля структуры класса
%   ---------------------
%   key       ключ латиницей; он же имя папки в датасете
%   name      человекочитаемое название для интерфейса и отчёта
%   isCurve   true у настоящих кривых, false у класса-отказа scribble
%   closed    замкнута ли кривая в своей канонической форме
%   nStrokes  сколько отдельных штрихов рисует человек (у гиперболы два)
%   hasAngle  нужно ли вообще определять угол поворота
%   symDeg    период поворотной симметрии в градусах; NaN означает, что
%             период зависит от дискретного параметра (случай розы)
%   shape     параметры формы, переживающие нормализацию: имя и диапазон
%   kValues   допустимые значения дискретного параметра (лепестки розы)
%   distort   множитель силы имитации руки; у кривых с тонкой геометрией
%             он меньше, иначе класс разрушается деформацией
%   aniso     собственный диапазон анизотропного растяжения; пустое поле
%             означает «взять общий из cnConfig». Переопределять его
%             приходится там, где растяжение меняет не вид кривой, а её
%             параметр: растянутая окружность — это эллипс, а растянутый
%             эллипс имеет уже другое отношение полуосей, то есть неверную
%             разметку
%   refine    способ уточняющей подгонки: "conic" — алгебраический МНК по
%             общему уравнению второго порядка, "nlls" — нелинейный МНК,
%             "none" — подгонка не выполняется
%   nReg      число выходов регрессионной головы
%   nCls      число выходов классификационной головы регрессора
%
%   О составе выходов регрессора
%   ----------------------------
%   Первые три выхода одинаковы у всех классов: dx, dy, ds — поправки к
%   центру и масштабу, полученным по габаритной рамке. Рамка, посчитанная
%   по дрожащей от руки линии, смещена и завышена, и эта поправка её
%   исправляет. Далее идут параметры формы из поля shape. Последними, если
%   hasAngle истинно, идут косинус и синус приведённого угла: угол нельзя
%   предсказывать одним числом, потому что 0 и 360 градусов — это один и
%   тот же поворот, а для функции потерь они максимально далеки.
%
%   Приведённый угол — это угол, умноженный на кратность симметрии
%   360/symDeg. Без такого приведения сеть получала бы разные целевые
%   значения для визуально одинаковых картинок и не сошлась бы. У розы
%   кратность равна k, поэтому её угол приводится только после того, как
%   определено число лепестков.
%
%   См. также CNCONFIG, CNSAMPLEPARAMS, CNCURVEPOINTS.

arguments
    sel = []
end

persistent C
if isempty(C)
    C = buildClasses();
end

if isempty(sel)
    out = C;
    return
end

if isnumeric(sel)
    if any(sel < 1 | sel > numel(C) | mod(sel,1) ~= 0)
        error("cnClasses:badIndex", ...
            "Номер класса должен быть целым от 1 до %d.", numel(C));
    end
    out = C(sel);
    return
end

sel = string(sel);
if sel == "table"
    out = summaryTable(C);
    return
end

idx = find([C.key] == sel, 1);
if isempty(idx)
    error("cnClasses:unknownKey", ...
        "Неизвестный класс «%s». Доступны: %s.", sel, join([C.key], ", "));
end
out = C(idx);
end


% =======================================================================
%  Описание классов
% =======================================================================
function C = buildClasses()

% --- кривые второго порядка -------------------------------------------

% Окружность полностью определяется габаритной рамкой: после нормализации
% у неё не остаётся ни формы, ни угла. Регрессор здесь уточняет только
% положение центра и радиус.
%
% Общая анизотропия для окружности отключена и заменена узкой: растяжение
% 0.85–1.15 по осям превратило бы её в эллипс с вытянутостью до 1.35, то
% есть в чужой класс с чужой меткой. Диапазон 0.97–1.03 даёт максимум 1.06
% и остаётся по свою сторону границы CIRCLEELLIPSEBOUND.
C = mk("circle", "Окружность", ...
        "hasAngle", false, "symDeg", 0, ...
        "aniso",    [0.97 1.03], ...
        "refine",   "conic");

% Окружность и эллипс — непрерывное семейство, объективного разрыва между
% ними не существует, поэтому граница проводится соглашением. Где именно её
% провести — вопрос не вкуса, а различимости: см. измерения в
% CIRCLEELLIPSEBOUND.
%
% Овалы с вытянутостью между 1.06 и 1.4 не порождаются ни одним классом. Это
% сознательный выбор: там сигнал тонет в дрожании руки, и примеры из этой
% полосы были бы для сети противоречивым шумом. Живой ввод, попавший в неё,
% будет отнесён к окружности — что и есть верный ответ, потому что от руки
% такой овал от круга не отличить.
%
% Анизотропия здесь отключена совсем: она меняет не вид кривой, а её
% вытянутость, то есть портит целевое значение для регрессора. Эту степень
% свободы уже покрывает сам параметр elong.
%
% Параметром служит вытянутость a/b, а не обратное ей отношение полуосей, и
% разыгрывается она логарифмически. Причина видна на глаз: при равномерном
% розыгрыше больше половины эллипсов получаются почти круглыми, потому что
% разница между 1.2 и 2.0 заметна, а между 4.2 и 5.0 — нет.
C(end+1) = mk("ellipse", "Эллипс", ...
        "symDeg", 180, ...
        "shape",  par("elong", circleEllipseBound(), 5.0, "log"), ...
        "aniso",  [1 1], ...
        "refine", "conic");

% Параболу рисуем в канонической форме y = x^2/2 при x от -L до L. После
% равномерного вписывания в кадр от неё остаётся ровно одна степень
% свободы — пропорция ветвей, она же L. Фокальный параметр восстанавливается
% потом из L и размера габаритной рамки.
C(end+1) = mk("parabola", "Парабола", ...
        "closed", false, ...
        "shape",   par("halfLength", 1.0, 4.0), ...
        "distort", 0.70, ...
        "refine",  "conic");

% Две ветви — это два отдельных движения руки, отсюда nStrokes = 2.
% Параметр b задаёт раствор ветвей, uMax — насколько далеко человек их увёл.
C(end+1) = mk("hyperbola", "Гипербола", ...
        "closed",   false, ...
        "nStrokes", 2, ...
        "symDeg",   180, ...
        "shape",    [par("b", 0.40, 1.80), par("uMax", 1.10, 1.80)], ...
        "distort",  0.50, ...
        "refine",   "conic");

% --- спирали ----------------------------------------------------------

% Шаг спирали после нормализации не наблюдаем, наблюдаемо только число
% витков.
%
% Нижняя граница опущена до 1.2 витка после проверки на живом вводе.
% Раньше стояло 2.5, и спираль в полтора витка — вполне обычный рисунок —
% не встречалась сети ни разу. Визуально это большая петля с маленькой
% внутри, то есть улитка Паскаля, и именно так живой ввод и распознавался.
% Взаимная путаница двух спиралей при малом числе витков неизбежна, но это
% честная ошибка внутри родственной пары, а не грубый промах в чужой класс.
C(end+1) = mk("archSpiral", "Спираль Архимеда", ...
        "closed", false, ...
        "shape",  par("turns", 1.2, 5.0));

% Логарифмическую от архимедовой отличает только закон роста витков.
C(end+1) = mk("logSpiral", "Логарифмическая спираль", ...
        "closed", false, ...
        "shape",  [par("growth", 0.23, 0.50), par("turns", 1.0, 3.5)]);

% --- прочие -----------------------------------------------------------

% Число лепестков — дискретный параметр, поэтому его предсказывает отдельная
% классификационная голова, а не регрессия: сеть, обученная выдавать k
% числом, на сомнительных примерах ответит что-нибудь вроде 4.2, и толку от
% этого не будет.
% Период симметрии розы равен 360/k, то есть определяется только после
% выбора k — отсюда NaN в symDeg.
% Лепестки — тонкая геометрия, сильная деформация её съедает, поэтому
% множитель distort понижен.
C(end+1) = mk("rose", "Роза Гранди", ...
        "symDeg",  NaN, ...
        "kValues", [3 5], ...
        "distort", 0.35, ...
        "aniso",   [0.95 1.05]);

% Лемниската Бернулли с точностью до подобия одна, свободной формы у неё
% нет — остаётся только угол. Однако у реальных рукописных лемнискат петли
% почти всегда отличаются по размеру. Вместо того чтобы делать асимметрию
% параметром формы (что потребовало бы переобучения регрессора), мы
% добавляем её как специальное искажение в cnHandDistort. Амплитуда
% искажения задаётся здесь, а само искажение применяется в cnHandDistort.
C(end+1) = mk("lemniscate", "Лемниската", ...
        "symDeg",  180, ...
        "shape",   par("asymmetry", 0.60, 1.67), ... % 1.0 = симметричная
        "distort", 0.50, ...
        "aniso",   [0.95 1.05]);

% Циклоида по своей природе тянется вдоль прямой, число арок задаёт
% вытянутость картинки. Дробные значения допустимы: человек вполне может
% оборвать рисунок на середине арки.
C(end+1) = mk("cycloid", "Циклоида", ...
        "closed",  false, ...
        "shape",   par("arches", 1.0, 3.0), ...
        "distort", 0.60);

% Опознавательный признак астроиды — четыре острия. Деформация их
% сглаживает и превращает фигуру в квадрат с вогнутыми сторонами, поэтому
% сила искажения понижена.
C(end+1) = mk("astroid", "Астроида", ...
        "symDeg",  90, ...
        "distort", 0.50, ...
        "aniso",   [0.95 1.05]);

% Опознавательный признак кардиоиды — остриё, то самое место, где кривая
% возвращается в начало координат. Деформация его сглаживает, и кардиоида
% превращается в окружность, то есть в чужой класс. Множитель подобран по
% просмотру примеров: при 0.45 остриё пропадало примерно у четверти.
C(end+1) = mk("cardioid", "Кардиоида", ...
        "distort", 0.28);

% Улитка Паскаля при b = a вырождается в кардиоиду. Нижняя граница
% отношения b/a держит внутреннюю петлю заметной, иначе два класса
% сливаются.
C(end+1) = mk("limacon", "Улитка Паскаля", ...
        "shape",   par("ratio", 1.25, 3.00), ...
        "distort", 0.55);

% --- класс-отказ ------------------------------------------------------

% Всё, что не является ни одной из двенадцати кривых. Регрессор для него не
% обучается: подбирать нечего, конвейер на этом классе останавливается и
% сообщает пользователю, что кривая не опознана.
C(end+1) = mk("scribble", "Не распознано", ...
        "isCurve",  false, ...
        "closed",   false, ...
        "hasAngle", false, ...
        "symDeg",   0, ...
        "refine",   "none");

% Размеры выходных слоёв регрессора выводятся из описания, а не задаются
% руками — иначе они разъедутся при первой же правке параметров.
for i = 1:numel(C)
    if C(i).isCurve
        C(i).nReg = 3 + numel(C(i).shape) + 2*C(i).hasAngle;
        C(i).nCls = numel(C(i).kValues);
    end
end
end


% =======================================================================
%  Вспомогательные конструкторы
% =======================================================================
function c = mk(key, name, varargin)
%MK  Описание класса: значения по умолчанию плюс правки парами
%    "имя поля", значение.

c = struct( ...
    "key",      string(key), ...
    "name",     string(name), ...
    "isCurve",  true, ...
    "closed",   true, ...
    "nStrokes", 1, ...
    "hasAngle", true, ...
    "symDeg",   360, ...
    "shape",    {emptyPar()}, ...   % фигурные скобки обязательны: иначе
    "kValues",  {[]}, ...           % struct() создаст массив структур
    "distort",  1.0, ...
    "aniso",    {[]}, ...        % пусто — берётся общий из cnConfig
    "refine",   "nlls", ...
    "nReg",     0, ...
    "nCls",     0);

if mod(numel(varargin), 2) ~= 0
    error("cnClasses:badPairs", ...
        "Правки задаются парами «имя поля», значение (класс %s).", key);
end
for i = 1:2:numel(varargin)
    f = string(varargin{i});
    if ~isfield(c, f)
        error("cnClasses:badField", "У класса %s нет поля «%s».", key, f);
    end
    c.(f) = varargin{i+1};
end
end


function b = circleEllipseBound()
%CIRCLEELLIPSEBOUND  Граница между окружностью и эллипсом по вытянутости.
%
%   Кривая с отношением большой полуоси к малой меньше b считается
%   окружностью, больше b — эллипсом. Объективного разрыва между этими
%   классами не существует, поэтому граница задаётся соглашением, но
%   задаётся ровно в одном месте: и верхний предел вытянутости окружности,
%   и нижний предел вытянутости эллипса берутся отсюда, чтобы между
%   классами не образовалось зазора.
%
%   Значение выбрано не на глаз, а по измерениям. На датасете с границей
%   1.15 обученный классификатор показал такую точность на эллипсах в
%   зависимости от их вытянутости:
%
%       1.15 – 1.3    16.8 %
%       1.3  – 1.5    48.9 %
%       1.5  – 1.8    89.0 %
%       1.8  – 2.4   100.0 %
%       2.4  – 5.0   100.0 %
%
%   Причина видна, если перевести в пиксели. Кривая вписана в кадр 160
%   пикселей. Вытянутость 1.15 означает эллипс 160 на 139 — отличие от круга
%   в 21 пиксель, тогда как деформация руки гуляет линию на десять-двадцать
%   пикселей. Полезный сигнал того же порядка, что шум, и различить их
%   нельзя в принципе — ни сетью, ни глазом.
%
%   При 1.4 отличие составляет уже 46 пикселей, вдвое-втрое больше дрожания.
%
%   Значение 1.4 — сознательный компромисс. Граница 1.6 дала бы класс,
%   который сеть знает почти идеально, но овал с вытянутостью 1.5
%   возвращался бы пользователю как окружность. При 1.4 класс покрывает
%   более широкий диапазон того, что человек назовёт эллипсом, ценой
%   нескольких процентов точности на самых круглых его представителях. Эти
%   проценты — не дефект реализации, а плата за границу, проведённую ближе
%   к пределу различимости.
%
%   Отсюда важное следствие: величину границы диктует не математика, а сила
%   искажения. Уменьшится дрожание — границу можно будет опустить.

b = 1.4;
end


function p = par(name, lo, hi, scale)
%PAR  Описание одного непрерывного параметра формы и его диапазона.
%
%   scale  "lin" (по умолчанию) или "log" — как разыгрывать значение.
%
%   Логарифмическая шкала нужна там, где параметр воспринимается глазом
%   мультипликативно. Вытянутость эллипса тому пример: разница между 1.2 и
%   2.0 бросается в глаза, а между 4.2 и 5.0 практически незаметна. При
%   равномерном розыгрыше половина эллипсов оказывается почти круглой, и
%   класс без нужды придвигается к окружности.

arguments
    name  (1,1) string
    lo    (1,1) double
    hi    (1,1) double
    scale (1,1) string = "lin"
end

if lo >= hi
    error("cnClasses:badRange", ...
        "Пустой диапазон у параметра «%s»: %g не меньше %g.", name, lo, hi);
end
if ~ismember(scale, ["lin","log"])
    error("cnClasses:badScale", ...
        "Шкала параметра «%s» должна быть lin или log.", name);
end
if scale == "log" && lo <= 0
    error("cnClasses:badLogRange", ...
        "Логарифмическая шкала требует положительного диапазона («%s»).", name);
end
p = struct("name", name, "lo", lo, "hi", hi, "scale", scale);
end


function p = emptyPar()
%EMPTYPAR  Пустой массив параметров с правильным набором полей.

p = par("dummy", 0, 1);
p(1) = [];
end


function T = summaryTable(C)
%SUMMARYTABLE  Сводка по классам в виде таблицы, для беглого просмотра.

n = numel(C);
shapeNames = strings(n,1);
kText      = strings(n,1);
for i = 1:n
    if isempty(C(i).shape)
        shapeNames(i) = "—";
    else
        shapeNames(i) = join([C(i).shape.name], ", ");
    end
    if isempty(C(i).kValues)
        kText(i) = "—";
    else
        kText(i) = join(string(C(i).kValues), "/");
    end
end

T = table( ...
    (1:n).', [C.key].', [C.name].', [C.closed].', [C.nStrokes].', ...
    [C.symDeg].', shapeNames, kText, [C.distort].', [C.refine].', ...
    [C.nReg].', [C.nCls].', ...
    VariableNames = ["N","ключ","название","замкнута","штрихов", ...
                     "симметрия","параметры формы","k","деформация", ...
                     "подгонка","выходов рег","выходов кл"]);
end