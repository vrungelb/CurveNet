end

function p = par(name, lo, hi, scale)
arguments
    name (1,1) string
    lo (1,1) double
    hi (1,1) double
    scale (1,1) string = "lin"
end

if lo >= hi
    error("cnClasses:badRange", "Неверный диапазон «%s»: %g >= %g.", name, lo, hi);
end
if ~ismember(scale, ["lin","log"])
    error("cnClasses:badScale", "Шкала параметра «%s» должна быть 'lin' или 'log'.", name);
end
if scale == "log" && lo <= 0
    error("cnClasses:badLogRange", "Для логарифмической шкалы «%s» нужен диапазон > 0.", name);
end
p = struct("name", name, "lo", lo, "hi", hi, "scale", scale);
end

function p = emptyPar()
p = par("dummy", 0, 1);
p(1) = [];
end

function T = summaryTable(C)
n = numel(C);
shapeNames = strings(n,1);
kText = strings(n,1);

for i = 1:n
    if isempty(C(i).shape)
        shapeNames(i) = "—";
    else
        shapeNames(i) = join([C(i).shape.name], ", ");
    end

    if isempty(C(i).kValues)
        kText(i) = "—";
    else
        kText(i) = join(string(C(i).kValues), "/");
    end
end

T = table( ...
    (1:n).', [C.key].', [C.name].', [C.closed].', [C.nStrokes].', ...
    [C.symDeg].', shapeNames, kText, [C.distort].', ...
    VariableNames = ["N","ключ","название","замкнута","штрихов", ...
    "симметрия","параметры формы","k","деформация"]);
end