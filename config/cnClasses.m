%CNCLASSES Словарь классов.
function out = cnClasses(sel)

arguments
    sel = []
end

persistent C
if isempty(C)
    C = buildClasses();
end

if isempty(sel)
    out = C;
    return
end

if isnumeric(sel)
    if any(sel < 1 | sel > numel(C) | mod(sel,1) ~= 0)
        error("cnClasses:badIndex", "Номер класса должен быть целым от 1 до %d.", numel(C));
    end
    out = C(sel);
    return
end

sel = string(sel);
if any(strlength(sel) == 0)
    error("cnClasses:emptyKey", "Передан пустой ключ класса.");
end

if isscalar(sel)
    switch sel
        case "all"
            out = C;
            return
        case "table"
            out = summaryTable(C);
            return
        case "curves"
            out = C([C.isCurve]);
            return
    end
end

[ok, idx] = ismember(sel(:).', [C.key]);
if ~all(ok)
    bad = sel(~ok);
    error("cnClasses:unknownKey", "Неизвестный класс «%s». Доступны: %s.", bad(1), join([C.key], ", "));
end
out = C(idx);
end

