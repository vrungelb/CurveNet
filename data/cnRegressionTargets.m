function [Y, names] = cnRegressionTargets(key, opts)
%CNREGRESSIONTARGETS  Целевые векторы регрессора для одного класса.
%
%   [Y, names] = CNREGRESSIONTARGETS("ellipse")
%   Y          = CNREGRESSIONTARGETS(key, parallel = false)
%
%   Y      матрица N на nReg: строка на каждый пример класса, в том же
%          порядке, в каком строки этого класса идут в meta.mat
%   names  подписи столбцов
%
%   Поддержаны четыре кривые второго порядка: окружность, эллипс, парабола,
%   гипербола. Остальные классы добавляются ветвями в SHAPEANDANGLE.
%
%   Почему цели не берутся из рецепта
%   ---------------------------------
%   В таблице рецептов уже лежат и elong, и halfLength, и angleDeg. Но рецепт
%   описывает намерение генератора, а между ним и картинкой стоит аффинное
%   преобразование из CNHANDDISTORT. Скос меняет вытянутость эллипса и
%   направление его осей, наклоняет ось параболы, меняет раствор гиперболы.
%   Обучение на числах из рецепта — это обучение на слегка неверной
%   разметке.
%
%   Поэтому истинные параметры восстанавливаются заново: каноническая кривая
%   прогоняется через тот же аффинный шаг и то же вписывание в кадр, что и
%   весь рисунок. Упругая деформация и тремор при этом не применяются — это
%   шум поверх формы, и сеть должна видеть форму под шумом.
%
%   Из деформации возвращается только перенос: она двигает фигуру целиком,
%   иногда на величину порядка её размера, а кадр строится по сдвинутому
%   рисунку. Подробности в TARGETFOR.
%
%   Состав целевого вектора
%   -----------------------
%   Длина равна nReg класса: три числа у окружности, шесть у эллипса и
%   параболы, семь у гиперболы. Порядок всегда один.
%
%   dx, dy    смещение опорной точки от центра кадра, в долях кадра. Кадр
%             строится по габаритной рамке нарисованной линии, а она
%             смещена: дрожание выпирает неравномерно, отрывы пера съедают
%             куски контура. Эту ошибку рамки сеть и исправляет.
%   ds        логарифм отношения истинного размера к размеру рамки.
%             Логарифм потому, что величина мультипликативная.
%   форма     параметры из поля shape класса; логарифмические по разметке
%             CNCLASSES предсказываются в логарифме.
%   cos, sin  косинус и синус приведённого угла — угла, умноженного на
%             кратность симметрии 360/symDeg. Одним числом угол
%             предсказывать нельзя: 0 и 360 градусов это один поворот, а для
%             среднеквадратичной ошибки они максимально далеки.
%
%   Опорная точка у параболы — вершина, у остальных центр. И там и там это
%   образ начала канонических координат, так что CNCURVESHAPE строит кривую
%   обратно без оговорок.
%
%   Оговорка про параболу и гиперболу
%   ---------------------------------
%   Аффинное преобразование сдвигает вершину вдоль кривой, и нарисованная
%   дуга перестаёт быть симметричной относительно неё. Модель класса
%   симметричную дугу предполагает, поэтому целью берётся среднее по двум
%   ветвям. Расхождение выходит порядка десятой доли при halfLength от
%   единицы до четырёх — меньше, чем дрожание руки, но помнить о нём стоит.
%
%   Как проверить, что разметка не врёт
%   -----------------------------------
%   Смещения dx и dy должны укладываться в несколько сотых: это поправка к
%   рамке, а не произвольный сдвиг. Параметры формы обязаны лежать в
%   границах класса из CNCLASSES — у эллипса log(1.4) = 0.3377 и
%   log(5) = 1.6095. А ds должен коррелировать со scaleJit из рецепта.
%
%   См. также CNCLASSES, CNCURVESHAPE, CNHANDDISTORT, CNTRAINREGRESSOR.

arguments
    key           (1,1) string
    opts.parallel (1,1) logical = true
    opts.verbose  (1,1) logical = true
end

c = cnClasses(key);
if ~c.isCurve
    error("cnRegressionTargets:notCurve", ...
        "Класс «%s» не кривая, регрессор для него не обучается.", key);
end
if ~ismember(key, ["circle", "ellipse", "parabola", "hyperbola"])
    error("cnRegressionTargets:notImplemented", ...
        ["Поддержаны только кривые второго порядка. Для класса «%s» нужно " ...
         "дописать ветвь в SHAPEANDANGLE."], key);
end

cfg = cnConfig();
if ~isfile(cfg.paths.meta)
    error("cnRegressionTargets:noMeta", ...
        "Нет %s. Сначала cnBuildDataset.", cfg.paths.meta);
end

T = load(cfg.paths.meta, "meta").meta.table;
R = T(string(T.class) == key, :);
if isempty(R)
    error("cnRegressionTargets:noRows", ...
        "В датасете нет примеров класса «%s».", key);
end

recs = table2struct(R);
n    = numel(recs);
Y    = zeros(n, c.nReg);

fill   = 1 - 2*cfg.img.pad;
mult   = angleMultiplier(c);
closed = c.closed;

t0 = tic;
if opts.parallel && ~isempty(ver("parallel"))
    parfor i = 1:n
        Y(i,:) = targetFor(key, recs(i), fill, mult, closed);
    end
else
    for i = 1:n
        Y(i,:) = targetFor(key, recs(i), fill, mult, closed);
    end
end

names = targetNames(c);

if ~all(isfinite(Y(:)))
    error("cnRegressionTargets:nonFinite", ...
        "Среди целей есть NaN или Inf: %d штук.", sum(~isfinite(Y(:))));
end

if opts.verbose
    fprintf("Класс «%s»: %d целей по %d выходов, %.1f c\n", key, n, c.nReg, toc(t0));
    disp(array2table([min(Y); prctile(Y, [1 50 99]); max(Y)], ...
        VariableNames = names, ...
        RowNames = ["мин","1%","медиана","99%","макс"]));
end

% Без этого вызов без точки с запятой вываливает в окно все семь тысяч
% строк матрицы: результат возвращается всегда, даже когда его не просили.
if nargout == 0
    clear Y
end
end


% =======================================================================
function y = targetFor(key, rec, fill, mult, closed)
%TARGETFOR  Целевой вектор одного примера.

% --- кадр, в котором окажется картинка ---------------------------------
% Повторяет CNRENDER без растеризации: пиксели нам не нужны, нужно только
% преобразование кадра. На семи тысячах примеров это минуты против секунд.
ideal = cnCurvePoints(key, rec, rec.nPoints);
sDist = cnHandDistort(ideal, rec, closed);
sCut  = cnStrokeBreak(sDist, rec, closed);
[~, tf] = cnNormalize(sCut, rec);

% --- аффинная часть искажения, без упругой деформации -------------------
% Строго повторяет первый уровень CNHANDDISTORT, включая повторное
% центрирование после преобразования. Меняете тот файл — меняйте и здесь:
% расхождение будет тихим и проявится только как плохая точность.
X  = vertcat(ideal{:});
c0 = (max(X,[],1) + min(X,[],1)) / 2;

a = deg2rad(rec.angleDeg);
M = [rec.anisoX, rec.shear*rec.anisoY; ...
     0,          rec.anisoY];
Rm = [cos(a), -sin(a); ...
      sin(a),  cos(a)];
B  = Rm * M;
if isfield(rec, "flip") && rec.flip
    B = diag([-1 1]) * B;
end

Paff = (X - c0) * B.';
cAff = (max(Paff,[],1) + min(Paff,[],1)) / 2;

% --- выравнивание по сдвигу ---------------------------------------------
% Упругая деформация не только меняет форму: её крупная составляющая имеет
% ненулевое среднее и переносит фигуру целиком, иногда на величину порядка
% её размера. Картинке это безразлично — нормализация всё равно вписывает
% нарисованное в кадр. А разметке нет: кадр строится по сдвинутому рисунку,
% и идеальная кривая, оставленная на месте, оказывается относительно кадра
% где угодно. Без поправки каждый девятый эллипс получал смещение центра
% больше десятой доли кадра, а худший — восемь десятых.
%
% Гнаться за деформацией не надо, снимается только перенос: как разность
% средних, пока точки ещё стоят в взаимно однозначном соответствии, то есть
% до разрывов из CNSTROKEBREAK.
shift = mean(vertcat(sDist{:}), 1) - mean(Paff - cAff, 1);

toFrame = @(Z) ((Z - c0) * B.' - cAff + shift - tf.center) / tf.scale ...
               + 0.5 + tf.offset;

[shape, th, refPt] = shapeAndAngle(key, rec, B / tf.scale);

Q  = toFrame(X);            % идеальная кривая в кадре
Q0 = toFrame(refPt);        % её опорная точка

dxy = Q0 - 0.5;
ext = max(max(Q,[],1) - min(Q,[],1));
ds  = log(ext / fill);

if isempty(th)
    y = [dxy, ds, shape];
else
    y = [dxy, ds, shape, cos(mult*th), sin(mult*th)];
end
end


% =======================================================================
function [shape, th, refPt] = shapeAndAngle(key, rec, L)
%SHAPEANDANGLE  Параметры формы, угол и опорная точка для класса.
%
%   L      линейное отображение канонических координат в кадр, без переноса
%   shape  значения параметров формы, пустой массив если их нет
%   th     угол поворота канонической кривой, пустой если класса без угла
%   refPt  опорная точка в канонических координатах
%
%   Сюда добавляются новые классы. Всё, что выше, от класса не зависит.

refPt = [0 0];

switch key
    case "circle"
        % Ни формы, ни угла: после вписывания в кадр остаются только
        % положение и размер.
        %
        % После аффинного шага идеальная окружность окружностью быть
        % перестаёт — анизотропия и скос делают из неё слегка сплюснутый
        % эллипс. Диапазоны в CNCLASSES подобраны так, чтобы это отклонение
        % не переползало границу с эллипсом, поэтому моделью остаётся
        % окружность, а сплющивание идёт в тот же разряд, что дрожание.
        shape = zeros(1,0);
        th    = [];

    case "ellipse"
        % Образ окружности под линейным отображением — снова эллипс, и
        % сингулярное разложение даёт его точно: сингулярные числа это
        % полуоси, левые сингулярные векторы — направления осей. Проверено
        % на датасете: совпадает с радиусами точек до четвёртого знака.
        G = L * diag([1, 1/rec.elong]);
        [U, Sv, ~] = svd(G);
        sig = diag(Sv);

        shape = log(sig(1) / sig(2));
        th    = atan2(U(2,1), U(1,1));

    case "parabola"
        % Каноническая точка (t, t²/2) переходит в t·L₁ + (t²/2)·L₂, где
        % L₁ и L₂ — столбцы отображения. Значит ось кривой направлена вдоль
        % L₂ — при квадратичном члене стоит именно он.
        L1 = L(:,1);
        L2 = L(:,2);
        n2 = norm(L2);
        e2 = L2 / n2;

        % Вершина — точка, где касательная перпендикулярна оси. Касательная
        % равна L₁ + t·L₂, отсюда параметр вершины.
        tv = -(L1.' * L2) / n2^2;
        refPt = [tv, 0.5*tv^2];

        % Поперечная составляющая L₁ задаёт, насколько кривая растянута
        % вдоль своей ветви. В собственных осях получается y = x²/(2p) с
        % p = alpha²/|L₂|, а половина размаха ветвей — halfLength·|L₂|/alpha.
        alpha = norm(L1 - (L1.' * e2) * e2);
        shape = rec.halfLength * n2 / alpha;

        % Каноническая парабола раскрыта вверх, поэтому поворот измеряется
        % от оси y, а не от оси x.
        th = atan2(e2(2), e2(1)) - pi/2;

    case "hyperbola"
        % Каноническая гипербола задаётся формой pᵀ·diag(1, −1/b²)·p = 1.
        % После отображения q = L·p форма переходит в L⁻ᵀ·G·L⁻¹, и её
        % собственные числа дают полуоси: положительное — действительную,
        % отрицательное — мнимую.
        G = diag([1, -1/rec.b^2]);
        Mq = (L.') \ G / L;
        Mq = (Mq + Mq.') / 2;              % симметрия после деления

        [V, Lm] = eig(Mq);
        lam = diag(Lm);
        [~, ip] = max(lam);
        im = 3 - ip;

        aH = 1 / sqrt(lam(ip));
        bH = 1 / sqrt(-lam(im));

        % Размах по параметру u аффинное отображение сохраняет: переход
        % между двумя гиперболами в их собственных осях — это гиперболический
        % поворот, а он лишь сдвигает u. Поэтому uMax берётся из рецепта.
        shape = [bH/aH, rec.uMax];
        th    = atan2(V(2,ip), V(1,ip));

    otherwise
        error("cnRegressionTargets:notImplemented", ...
            "Нет ветви для класса «%s».", key);
end
end


% =======================================================================
function mult = angleMultiplier(c)
%ANGLEMULTIPLIER  Кратность симметрии для приведения угла.
%
%   У классов без угла symDeg равен нулю, и деление 360/symDeg дало бы
%   бесконечность, которая тихо расползлась бы по вычислениям.

if ~c.hasAngle || c.symDeg <= 0
    mult = NaN;
else
    mult = 360 / c.symDeg;
end
end


% =======================================================================
function names = targetNames(c)
%TARGETNAMES  Подписи столбцов целевой матрицы.

names = ["dx", "dy", "ds"];
for i = 1:numel(c.shape)
    p = c.shape(i);
    if p.scale == "log"
        names(end+1) = "log " + p.name; %#ok<AGROW>
    else
        names(end+1) = p.name; %#ok<AGROW>
    end
end
if c.hasAngle
    names = [names, "cos", "sin"];
end
end
