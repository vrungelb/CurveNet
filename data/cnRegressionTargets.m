function [Y, names] = cnRegressionTargets(key, opts)
%CNREGRESSIONTARGETS  Целевые векторы регрессора для одного класса.
%
%   [Y, names] = CNREGRESSIONTARGETS("ellipse")
%   Y          = CNREGRESSIONTARGETS(key, parallel = false)
%
%   Y      матрица N на nReg: строка на каждый пример класса, в том же
%          порядке, в каком строки этого класса идут в meta.mat
%   names  подписи столбцов, для отчётов и отладки
%
%   Что здесь считается и почему это не берётся из рецепта напрямую
%   ---------------------------------------------------------------
%   Соблазн взять целевые значения прямо из таблицы рецептов велик: там уже
%   лежат и elong, и angleDeg. Но рецепт описывает намерение генератора, а
%   не то, что в итоге оказалось на картинке.
%
%   Между рецептом и картинкой стоит аффинное преобразование из
%   CNHANDDISTORT. Скос меняет и вытянутость эллипса, и направление его осей.
%   Обучать сеть на числах из рецепта значит обучать её на слегка неверной
%   разметке — а потом удивляться, что уточняющая подгонка систематически
%   спорит с сетью.
%
%   Поэтому истинные параметры восстанавливаются заново: каноническая кривая
%   из CNCURVEPOINTS прогоняется через тот же аффинный шаг, что и в
%   CNHANDDISTORT, а затем через то же вписывание в кадр, что и весь рисунок.
%   Упругая деформация и тремор при этом не применяются намеренно — это шум
%   поверх формы, и предсказывать сеть должна форму под шумом, а не вместе с
%   ним.
%
%   Из деформации, однако, приходится вернуть одну составляющую — перенос.
%   Подробности в TARGETFOR, но коротко: деформация двигает фигуру целиком,
%   иногда на величину порядка её собственного размера, а кадр строится по
%   сдвинутому рисунку. Без этой поправки идеальная кривая оказывается
%   относительно кадра где угодно, вплоть до выхода за его пределы.
%
%   Состав целевого вектора
%   -----------------------
%   Длина вектора равна nReg класса и у разных классов разная: у окружности
%   три числа, у эллипса шесть. Порядок всегда один и тот же.
%
%   dx, dy    смещение истинного центра кривой от центра кадра, в долях
%             кадра. Кадр строится по габаритной рамке нарисованной линии, а
%             она смещена: дрожание выпирает наружу неравномерно, отрывы
%             пера съедают куски контура. Вот эту ошибку рамки сеть и
%             исправляет.
%   ds        логарифм отношения истинного размера к размеру рамки. Логарифм
%             потому, что величина мультипликативная: завышение рамки в
%             полтора раза и занижение в полтора раза должны быть одинаково
%             далеки от нуля.
%   форма     параметры из поля shape класса, сколько бы их ни было. Те, что
%             размечены в CNCLASSES как логарифмические, предсказываются в
%             логарифме — по той же причине, по которой они логарифмически
%             разыгрываются. У окружности этой части нет вовсе.
%   cos, sin  косинус и синус приведённого угла, то есть угла, умноженного
%             на кратность симметрии 360/symDeg. Одним числом угол
%             предсказывать нельзя: 0 и 360 градусов — один поворот, а для
%             среднеквадратичной ошибки они максимально далеки. У классов с
%             hasAngle = false этой части тоже нет.
%
%   Как проверить, что разметка не врёт
%   -----------------------------------
%   Три признака, каждый виден в печатаемой сводке. Смещения dx и dy должны
%   укладываться в несколько сотых: это поправка к рамке, а не произвольный
%   сдвиг. Логарифм параметра формы обязан лежать ровно в границах,
%   объявленных для класса в CNCLASSES, — у эллипса это log(1.4) = 0.3377 и
%   log(5) = 1.6095. А ds должен заметно коррелировать со scaleJit из
%   рецепта: именно остаточный разброс масштаба он и правит.
%
%   Поддержаны окружность и эллипс. Остальные классы добавляются отдельными
%   ветвями в SHAPEANDANGLE: у каждого своя связь между рецептом и
%   наблюдаемой геометрией, и общего выражения для неё нет.
%
%   См. также CNCLASSES, CNHANDDISTORT, CNNORMALIZE, CNTRAINREGRESSOR.

arguments
    key           (1,1) string
    opts.parallel (1,1) logical = true
    opts.verbose  (1,1) logical = true
end

c = cnClasses(key);
if ~c.isCurve
    error("cnRegressionTargets:notCurve", ...
        "Класс «%s» не кривая, регрессор для него не обучается.", key);
end
if ~ismember(key, ["circle", "ellipse"])
    error("cnRegressionTargets:notImplemented", ...
        ["Поддержаны только окружность и эллипс. Для класса «%s» нужно " ...
         "дописать свою ветвь в SHAPEANDANGLE."], key);
end

cfg = cnConfig();
if ~isfile(cfg.paths.meta)
    error("cnRegressionTargets:noMeta", ...
        "Нет %s. Сначала cnBuildDataset.", cfg.paths.meta);
end

T = load(cfg.paths.meta, "meta").meta.table;
R = T(string(T.class) == key, :);
if isempty(R)
    error("cnRegressionTargets:noRows", ...
        "В датасете нет примеров класса «%s».", key);
end

recs = table2struct(R);
n    = numel(recs);
Y    = zeros(n, c.nReg);

fill   = 1 - 2*cfg.img.pad;    % какую долю кадра занимает габаритная рамка
mult   = angleMultiplier(c);   % кратность симметрии, NaN если угла нет
closed = c.closed;

t0 = tic;
if opts.parallel && ~isempty(ver("parallel"))
    parfor i = 1:n
        Y(i,:) = targetFor(key, recs(i), fill, mult, closed);
    end
else
    for i = 1:n
        Y(i,:) = targetFor(key, recs(i), fill, mult, closed);
    end
end

names = targetNames(c);

if ~all(isfinite(Y(:)))
    error("cnRegressionTargets:nonFinite", ...
        "Среди целей есть NaN или Inf: %d штук.", sum(~isfinite(Y(:))));
end

if opts.verbose
    fprintf("Класс «%s»: %d целей по %d выходов, %.1f c\n", key, n, c.nReg, toc(t0));
    disp(array2table([min(Y); prctile(Y, [1 50 99]); max(Y)], ...
        VariableNames = names, ...
        RowNames = ["мин","1%","медиана","99%","макс"]));
end
end


% =======================================================================
function y = targetFor(key, rec, fill, mult, closed)
%TARGETFOR  Целевой вектор одного примера.

% --- кадр, в котором окажется картинка ---------------------------------
% Повторяет CNRENDER без последнего шага: растеризация нужна только для
% пикселей, а нам нужно преобразование кадра, и считать её ради него было бы
% впустую потраченным временем. На семи тысячах примеров разница между
% полным рендером и этим сокращённым — минуты против секунд.
ideal = cnCurvePoints(key, rec, rec.nPoints);
sDist = cnHandDistort(ideal, rec, closed);
sCut  = cnStrokeBreak(sDist, rec, closed);
[~, tf] = cnNormalize(sCut, rec);

% --- аффинная часть искажения, без упругой деформации -------------------
% Строго повторяет первый уровень CNHANDDISTORT, включая повторное
% центрирование после преобразования. Если тот файл менять, надо менять и
% здесь: расхождение будет тихим и проявится только как необъяснимо плохая
% точность регрессора.
X  = vertcat(ideal{:});
c0 = (max(X,[],1) + min(X,[],1)) / 2;

a = deg2rad(rec.angleDeg);
M = [rec.anisoX, rec.shear*rec.anisoY; ...
     0,          rec.anisoY];
Rm = [cos(a), -sin(a); ...
      sin(a),  cos(a)];
B  = Rm * M;
if isfield(rec, "flip") && rec.flip
    B = diag([-1 1]) * B;
end

Paff = (X - c0) * B.';
cAff = (max(Paff,[],1) + min(Paff,[],1)) / 2;

% --- выравнивание по сдвигу ---------------------------------------------
% Упругая деформация — это не только изменение формы. Её крупная
% составляющая имеет ненулевое среднее и переносит фигуру целиком, иногда на
% величину порядка её собственного размера. Для картинки это безразлично:
% нормализация всё равно вписывает нарисованное в кадр по габаритной рамке.
% А вот для разметки — нет: кадр строится по сдвинутому рисунку, и идеальная
% кривая, оставленная на прежнем месте, оказывается относительно этого кадра
% где угодно. На датасете эллипсов без этой поправки каждый девятый пример
% получал смещение центра больше десятой доли кадра, а худший — восемь
% десятых, то есть целевой центр лежал за пределами картинки.
%
% Гнаться за деформацией не надо, надо снять только перенос. Он находится
% как разность средних: точки идеальной кривой и точки искажённой стоят во
% взаимно однозначном соответствии, пока CNSTROKEBREAK не выбросил часть из
% них, поэтому среднее берётся до разрывов.
%
% Что здесь получается по смыслу: целью становится не «идеальная кривая из
% рецепта», а «идеальная кривая, приложенная к рисунку наилучшим образом по
% положению». Именно её и должна предсказывать сеть — то, что видно на
% картинке, а не то, что задумывал генератор.
shift = mean(vertcat(sDist{:}), 1) - mean(Paff - cAff, 1);

% Каноническая точка -> кадр сети, одним отображением.
toFrame = @(Z) ((Z - c0) * B.' - cAff + shift - tf.center) / tf.scale ...
               + 0.5 + tf.offset;

Q  = toFrame(X);               % идеальная кривая в кадре
Q0 = toFrame(zeros(1,2));      % её центр

dxy = Q0 - 0.5;
ext = max(max(Q,[],1) - min(Q,[],1));
ds  = log(ext / fill);

[shape, th] = shapeAndAngle(key, rec, B, tf);

if isempty(th)
    y = [dxy, ds, shape];
else
    y = [dxy, ds, shape, cos(mult*th), sin(mult*th)];
end
end


% =======================================================================
function [shape, th] = shapeAndAngle(key, rec, B, tf)
%SHAPEANDANGLE  Параметры формы и угол наклона для конкретного класса.
%
%   shape  строка значений параметров формы, пустая если их нет
%   th     угол наклона в радианах, пустой если класс его не имеет
%
%   Сюда добавляются новые классы. Всё, что выше, от класса не зависит:
%   центр и масштаб считаются одинаково для любой кривой.

switch key
    case "circle"
        % У окружности нет ни формы, ни угла: после вписывания в кадр от неё
        % остаются только положение и размер, а они уже посчитаны.
        %
        % Строго говоря, идеальная окружность после аффинного шага
        % окружностью быть перестаёт: анизотропия и скос делают из неё слегка
        % сплюснутый эллипс. Диапазоны в CNCLASSES подобраны так, чтобы это
        % отклонение не выходило за границу с классом эллипса, поэтому
        % моделью остаётся окружность, а сплющивание попадает в тот же
        % разряд, что дрожание руки, — в шум, который сеть должна
        % игнорировать.
        shape = zeros(1,0);
        th    = [];

    case "ellipse"
        % Каноническая кривая — образ единичной окружности под diag(1,1/elong);
        % значит в кадре она образ той же окружности под произведением матриц.
        % Сингулярные числа этого произведения и есть полуоси, а левые
        % сингулярные векторы — направления осей. Подгонять численно нечего:
        % проверено на датасете, наибольший и наименьший радиусы точек
        % совпадают с сингулярными числами до четвёртого знака.
        G = (B / tf.scale) * diag([1, 1/rec.elong]);
        [U, Sv, ~] = svd(G);
        sig = diag(Sv);

        shape = log(sig(1) / sig(2));           % истинная вытянутость
        th    = atan2(U(2,1), U(1,1));          % направление большой оси

    otherwise
        error("cnRegressionTargets:notImplemented", ...
            "Нет ветви для класса «%s».", key);
end
end


% =======================================================================
function mult = angleMultiplier(c)
%ANGLEMULTIPLIER  Кратность симметрии для приведения угла.
%
%   У классов без угла symDeg равен нулю, и прямое деление 360/symDeg даёт
%   бесконечность, которая потом тихо расползается по вычислениям. Поэтому
%   для них возвращается NaN, а пользоваться значением можно только внутри
%   проверки hasAngle.

if ~c.hasAngle || c.symDeg <= 0
    mult = NaN;
else
    mult = 360 / c.symDeg;
end
end


% =======================================================================
function names = targetNames(c)
%TARGETNAMES  Подписи столбцов целевой матрицы.

names = ["dx", "dy", "ds"];
for i = 1:numel(c.shape)
    p = c.shape(i);
    if p.scale == "log"
        names(end+1) = "log " + p.name; %#ok<AGROW>
    else
        names(end+1) = p.name; %#ok<AGROW>
    end
end
if c.hasAngle
    names = [names, "cos", "sin"];
end
end
