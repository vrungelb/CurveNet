function net = cnClassifierArch(numClasses, opts)
%CNCLASSIFIERARCH  Архитектура свёрточного классификатора кривых.
%
%   net = CNCLASSIFIERARCH(numClasses)
%   net = CNCLASSIFIERARCH(numClasses, width = 24, depth = 5)
%   net = CNCLASSIFIERARCH(..., dropout = 0.4)
%
%   Возвращает dlnetwork, готовую к обучению через trainnet.
%
%   Почему сеть своя, а не готовая предобученная
%   --------------------------------------------
%   Соблазн взять ResNet или EfficientNet и дообучить велик, но для этой
%   задачи они плохо подходят. Их первые слои настроены на текстуры и цвет
%   натуральных фотографий, а у нас одноканальные почти бинарные картинки,
%   где всё содержание — тонкая линия на пустом фоне. Полезного переноса
%   почти не будет, зато будет десяток миллионов параметров, которые надо
%   кормить данными.
%
%   Сеть с нуля здесь и уместнее, и честнее: задача простая по содержанию,
%   данных мы можем сгенерировать сколько угодно, а объяснить на защите
%   пятнадцать слоёв, которые сам написал, куда проще, чем чужую сеть на
%   полторы сотни.
%
%   Устройство
%   ----------
%   Пять ступеней, в каждой два свёрточных слоя 3x3 с нормализацией и ReLU,
%   затем прореживание вдвое. Размер идёт 160 - 80 - 40 - 20 - 10 - 5, число
%   каналов удваивается на каждой ступени.
%
%   Два слоя 3x3 подряд видят область 5x5, но требуют меньше параметров, чем
%   один слой 5x5, и содержат между собой нелинейность. Это стандартный
%   приём, и для линий он особенно уместен: важны локальные события —
%   изгиб, пересечение, острие, конец линии, — а они как раз укладываются в
%   такое окно.
%
%   Пакетная нормализация после каждой свёртки нужна не столько для
%   регуляризации, сколько для скорости: без неё сеть такой глубины сходится
%   заметно медленнее и требует аккуратного подбора темпа обучения.
%
%   Глобальное усреднение вместо выпрямления
%   ----------------------------------------
%   После последней ступени карта признаков 5x5x384 не выпрямляется в
%   вектор, а усредняется по пространству. Выпрямление дало бы почти
%   десять тысяч входов полносвязного слоя и с ними миллионы параметров,
%   которые сеть охотно потратит на запоминание конкретных примеров.
%
%   Усреднение к тому же снимает остаточную чувствительность к положению:
%   лепесток розы вносит одинаковый вклад, где бы в кадре он ни оказался.
%   После нормализации кривая и так вписана в кадр, но идеально это никогда
%   не выходит, и такой запас прочности не лишний.
%
%   Дропаут перед последним слоем — единственная явная регуляризация. Данных
%   у нас много и они разнообразны, поэтому сильная регуляризация не нужна,
%   но полностью без неё сеть начинает цепляться за мелкие артефакты
%   растеризации.
%
%   Именованные аргументы
%   ---------------------
%   width    число каналов первой ступени (по умолчанию 24)
%   depth    число ступеней (по умолчанию 5)
%   dropout  доля отключаемых связей перед классификатором
%
%   См. также CNTRAINCLASSIFIER, CNCONFIG.

arguments
    numClasses   (1,1) double {mustBeInteger, mustBePositive}
    opts.width   (1,1) double {mustBeInteger, mustBePositive} = 24
    opts.depth   (1,1) double {mustBeInteger, mustBePositive} = 5
    opts.dropout (1,1) double {mustBeInRange(opts.dropout, 0, 0.9)} = 0.35
end

cfg = cnConfig();
S   = cfg.img.size;

% Картинки хранятся как uint8; слой сам приводит их к диапазону 0..1.
% Делать это где-то ещё нельзя: живой ввод должен пройти ровно ту же
% подготовку, а он тоже идёт через этот слой.
layers = imageInputLayer([S S 1], ...
    Normalization = "rescale-zero-one", ...
    Name = "input");

ch = opts.width;
for k = 1:opts.depth
    layers = [layers; stage(k, ch)]; %#ok<AGROW>
    ch = min(ch*2, 512);        % потолок, чтобы верхние ступени не разбухли
end

layers = [layers
    globalAveragePooling2dLayer(Name = "gap")
    dropoutLayer(opts.dropout, Name = "drop")
    fullyConnectedLayer(numClasses, Name = "fc")
    softmaxLayer(Name = "softmax")];

net = dlnetwork(layers);
end


% =======================================================================
function L = stage(k, ch)
%STAGE  Одна ступень: две свёртки 3x3 и прореживание вдвое.

p = sprintf("s%d_", k);
L = [
    convolution2dLayer(3, ch, Padding = "same", Name = p + "conv1")
    batchNormalizationLayer(Name = p + "bn1")
    reluLayer(Name = p + "relu1")

    convolution2dLayer(3, ch, Padding = "same", Name = p + "conv2")
    batchNormalizationLayer(Name = p + "bn2")
    reluLayer(Name = p + "relu2")

    maxPooling2dLayer(2, Stride = 2, Name = p + "pool")];
end
