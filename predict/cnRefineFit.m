function F = cnRefineFit(key, strokes, opts)
%CNREFINEFIT  Уточнение параметров кривой алгебраическим МНК по точкам.
%
%   F = CNREFINEFIT("circle", strokes)
%   F = CNREFINEFIT("ellipse", strokes, nPoints = 600)
%
%   strokes  штрихи в координатах холста, как их отдаёт CNCANVASAPP
%
%   Поля результата
%   ---------------
%   ok        удалось ли подобрать кривую
%   status    "ok", "warn" или "reject" — по величине невязки
%   message   пояснение при отказе
%   points    точки подобранной кривой
%   params    центр, полуоси, наклон
%   equation  уравнение в координатах холста
%   general   то же в общем виде
%   residual  средняя невязка, доля характерного размера кривой
%   nUsed     сколько точек участвовало в окончательной подгонке
%
%   Зачем это нужно поверх регрессора
%   ---------------------------------
%   Регрессор систематически осторожничает. Он предсказывает поправку к
%   габаритной рамке, часть которой предсказать нельзя в принципе, и
%   среднеквадратичная ошибка в такой ситуации вознаграждает оценку,
%   стянутую к среднему. Отсюда завышение радиуса окружности процентов на
%   пять, которое видно и на датасете, и на живом вводе, и которое не
%   лечится ни дропаутом, ни числом эпох.
%
%   Подгонка работает с самими точками рисунка, а не с картинкой 160x160,
%   и потому не имеет этого недостатка. Для коник она к тому же
%   алгебраическая: решается напрямую, без итераций и без начального
%   приближения. Роль сети сводится к тому, чтобы назвать класс.
%
%   Начальное приближение от регрессора понадобится позже — спиралям и
%   розам, где алгебраического решения нет и работает только нелинейный
%   поиск, который из случайной точки расходится.
%
%   Как считается
%   -------------
%   Окружность: уравнение x² + y² + Dx + Ey + F = 0 линейно по D, E, F,
%   поэтому обычный МНК даёт ответ сразу.
%
%   Эллипс: метод Фицгиббона. Общее уравнение второй степени тоже линейно
%   по коэффициентам, но без ограничения МНК уводит решение к вырожденным
%   случаям — гиперболе или паре прямых. Ограничение 4AC − B² = 1
%   заставляет решение остаться эллипсом, и задача сводится к обобщённой
%   задаче на собственные значения. Используется вариант Халиржа и
%   Флуссера: он математически тот же, но не теряет точность на плохо
%   обусловленных матрицах.
%
%   Точки перед подгонкой центрируются и нормируются по разбросу. Без
%   этого матрица плана содержит четвёртые степени координат, и при
%   координатах порядка десяти обусловленность падает на несколько
%   порядков.
%
%   Отсев выбросов
%   --------------
%   Подгонка делается дважды. После первого прохода точки, отстоящие от
%   кривой дальше утроенной медианной невязки, отбрасываются, и подгонка
%   повторяется. Причина в том, что МНК квадратично штрафует отклонения, и
%   один случайный хвост от соскочившей руки перетягивает кривую заметно
%   сильнее, чем сотня нормальных точек.
%
%   Невязка
%   -------
%   Для окружности берётся точное расстояние от точки до кривой. Для
%   эллипса точное расстояние требует решения уравнения четвёртой степени
%   на каждую точку, поэтому используется приближение Сэмпсона: значение
%   многочлена, делённое на модуль его градиента. Вблизи кривой оно
%   совпадает с расстоянием с точностью до второго порядка, а это как раз
%   та область, где нам и важно.
%
%   Невязка делится на характерный размер кривой, то есть на корень из
%   произведения полуосей. Так она не зависит ни от масштаба рисунка, ни
%   от размера холста, и её можно сравнивать с порогами из cfg.refine.
%
%   См. также CNFITCURVE, CNCURVESHAPE, CNPREDICT.

arguments
    key          (1,1) string
    strokes      cell
    opts.nPoints (1,1) double {mustBeInteger, mustBePositive} = 600
end

F = struct("ok", false, "status", "reject", "message", "", ...
           "points", zeros(0,2), "params", struct(), ...
           "equation", "", "general", "", ...
           "residual", NaN, "nUsed", 0);

cfg = cnConfig();

if ~ismember(key, ["circle", "ellipse"])
    F.message = "Подгонка для этого класса не реализована.";
    return
end

% --- точки ---------------------------------------------------------------
P = vertcat(strokes{:});
P = P(all(isfinite(P), 2), :);
if size(P,1) < 8
    F.message = "Слишком мало точек для подгонки.";
    return
end

% --- нормировка ----------------------------------------------------------
% Центрирование и деление на разброс. Матрица плана содержит четвёртые
% степени координат, и без этого она плохо обусловлена.
c0 = mean(P, 1);
s0 = sqrt(mean(sum((P - c0).^2, 2)));
if s0 < eps
    F.message = "Рисунок вырожден.";
    return
end
Q = (P - c0) / s0;

% --- две подгонки с отсевом выбросов -------------------------------------
use = true(size(Q,1), 1);
g   = [];

for pass = 1:2
    gTry = fitOnce(key, Q(use,:));
    if isempty(gTry)
        break
    end
    g = gTry;

    if pass == 1
        d   = distTo(key, Q, g);
        thr = 3 * median(d);
        if thr > 0
            use = d <= thr;
        end
        if sum(use) < 8
            use = true(size(Q,1), 1);
            break
        end
    end
end

if isempty(g)
    F.message = "Подобрать кривую не удалось.";
    return
end

% --- обратно в координаты холста -----------------------------------------
ctr = g.center * s0 + c0;
a   = g.a * s0;
b   = g.b * s0;

if ~all(isfinite([ctr a b])) || a <= 0 || b <= 0
    F.message = "Подгонка разошлась.";
    return
end

S = cnCurveShape(key, ctr, a, b, g.th, nPoints = opts.nPoints);

F.points   = S.points;
F.params   = S.params;
F.equation = S.equation;
F.general  = S.general;

% --- невязка -------------------------------------------------------------
d = distTo(key, Q(use,:), g) * s0;
F.residual = mean(d) / sqrt(a*b);
F.nUsed    = sum(use);

if F.residual > cfg.refine.residualReject
    F.status  = "reject";
    F.message = "Линия слишком далека от кривой.";
elseif F.residual > cfg.refine.residualWarn
    F.status = "warn";
    F.ok     = true;
else
    F.status = "ok";
    F.ok     = true;
end
end


% =======================================================================
function g = fitOnce(key, Q)
%FITONCE  Одна подгонка. Возвращает центр, полуоси и наклон или пусто.

switch key
    case "circle"
        g = fitCircle(Q);
    case "ellipse"
        g = fitEllipse(Q);
end
end


% =======================================================================
function g = fitCircle(Q)
%FITCIRCLE  Окружность линейным МНК.
%
%   x² + y² + Dx + Ey + F = 0 линейно по D, E, F. Центр равен (−D/2, −E/2),
%   радиус — корню из суммы квадратов координат центра минус F.

g = [];
x = Q(:,1); y = Q(:,2);

A = [x, y, ones(numel(x),1)];
w = A \ (-(x.^2 + y.^2));

cx = -w(1)/2;
cy = -w(2)/2;
r2 = cx^2 + cy^2 - w(3);
if ~isfinite(r2) || r2 <= 0
    return
end

r = sqrt(r2);
g = struct("center", [cx cy], "a", r, "b", r, "th", 0);
end


% =======================================================================
function g = fitEllipse(Q)
%FITELLIPSE  Эллипс методом Фицгиббона в варианте Халиржа и Флуссера.
%
%   Ограничение 4AC − B² = 1 не даёт решению соскользнуть в гиперболу.
%   Разделение матрицы плана на квадратичную и линейную части позволяет
%   решить задачу без обращения плохо обусловленной матрицы целиком.

g = [];
x = Q(:,1); y = Q(:,2);

D1 = [x.^2, x.*y, y.^2];
D2 = [x, y, ones(numel(x),1)];

S1 = D1.' * D1;
S2 = D1.' * D2;
S3 = D2.' * D2;

if rcond(S3) < 1e-12
    return
end

T = -(S3 \ S2.');
M = S1 + S2 * T;

% Умножение на обратную матрицу ограничения, выписанное явно: она
% фиксированная и разреженная, обращать её численно незачем.
M = [M(3,:)/2; -M(2,:); M(1,:)/2];

[V, ~] = eig(M);
cond_ = 4*V(1,:).*V(3,:) - V(2,:).^2;
k = find(cond_ > 0, 1);
if isempty(k)
    return
end

a1 = V(:,k);
w  = real([a1; T*a1]);

g = conicToGeom(w);
end


% =======================================================================
function g = conicToGeom(w)
%CONICTOGEOM  От коэффициентов Ax² + Bxy + Cy² + Dx + Ey + F к геометрии.
%
%   Через матрицу квадратичной формы: центр находится из условия равенства
%   нулю градиента, полуоси и направления осей — из собственных чисел и
%   векторов. Это устойчивее, чем готовые формулы через дискриминант: там
%   легко перепутать, какая ветвь корня отвечает большой оси.

g = [];

A = w(1); B = w(2); C = w(3);
D = w(4); E = w(5); F = w(6);

M2 = [A, B/2; B/2, C];
if abs(det(M2)) < eps || det(M2) <= 0
    return                      % не эллипс
end

ctr = -M2 \ [D/2; E/2];
Fc  = F + [D/2, E/2] * ctr;
if Fc >= 0
    return                      % мнимый эллипс
end

[V, L] = eig(M2);
lam = diag(L);
if any(lam <= 0)
    return
end

ax = sqrt(-Fc ./ lam);          % полуоси по осям собственных векторов

% Большая полуось отвечает меньшему собственному числу.
[~, iMaj] = max(ax);
iMin = 3 - iMaj;

g = struct( ...
    "center", ctr.', ...
    "a",      ax(iMaj), ...
    "b",      ax(iMin), ...
    "th",     atan2(V(2,iMaj), V(1,iMaj)));
end


% =======================================================================
function d = distTo(key, Q, g)
%DISTTO  Расстояние от точек до подобранной кривой.

switch key
    case "circle"
        % Точное: модуль разности расстояния до центра и радиуса.
        d = abs(vecnorm(Q - g.center, 2, 2) - g.a);

    case "ellipse"
        % Приближение Сэмпсона. Точное расстояние до эллипса требует корней
        % уравнения четвёртой степени на каждую точку; вблизи кривой
        % приближение совпадает с ним до второго порядка, а нам важна
        % именно окрестность.
        R = [cos(g.th), sin(g.th); -sin(g.th), cos(g.th)];
        Z = (Q - g.center) * R.';
        u = Z(:,1)/g.a;
        v = Z(:,2)/g.b;

        val  = u.^2 + v.^2 - 1;
        grad = 2*hypot(u/g.a, v/g.b);
        grad(grad < eps) = eps;

        d = abs(val) ./ grad;
end
end
