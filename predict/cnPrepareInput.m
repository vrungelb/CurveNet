function [img, info] = cnPrepareInput(strokes, canvasSpan)
%CNPREPAREINPUT  Подготовка нарисованного на холсте к подаче в сеть.
%
%   [img, info] = CNPREPAREINPUT(strokes, canvasSpan)
%
%   strokes     массив ячеек со штрихами: точки мыши в координатах холста
%   canvasSpan  размер холста в тех же координатах (сторона квадрата)
%
%   img   картинка 160x160 uint8, готовая для сети; пустая, если ввод
%         отбракован
%   info  структура с результатом проверок и служебными данными
%
%   Поля info
%   ---------
%   ok           годится ли ввод для распознавания
%   message      человекочитаемое объяснение, если не годится
%   warning      предупреждение, не мешающее распознаванию
%   strokes      очищенные штрихи в нормализованном кадре
%   tf           преобразование обратно в координаты холста
%   nStrokes     сколько штрихов осталось после отсева
%   nDropped     сколько штрихов выброшено как мусорные
%   boxFrac      какую долю холста заняла габаритная рамка
%   thinness     отношение поперечного размера к продольному в главных осях
%   touchesEdge  упирается ли рисунок в границу холста
%
%   Главное требование к этому файлу
%   --------------------------------
%   Он обязан приводить рисунок ровно к тому же виду, в каком сеть видела
%   обучающие примеры. Не к похожему — к тому же. Поэтому здесь вызываются
%   те же самые CNRESAMPLEARC, CNNORMALIZE и CNRASTERIZE, что и в
%   генераторе датасета, с теми же настройками из CNCONFIG.
%
%   Расхождение здесь — худшая из возможных ошибок в такой задаче: картинки
%   выглядят одинаково, всё работает, а точность необъяснимо низкая.
%
%   Что делается и почему
%   ---------------------
%   Отсев мусорных штрихов. Случайный клик мимо или дёрнувшаяся мышь дают
%   точку или чёрточку в стороне от рисунка. Она попадает в габаритную
%   рамку, растягивает её вдвое, и сама кривая ужимается в четверть кадра.
%   Это самый вероятный способ развалить распознавание на ровном месте,
%   поэтому короткие штрихи выбрасываются до подсчёта рамки.
%
%   Проверка на вырожденность. Точка, микрочёрточка, почти прямая линия —
%   информации там физически нет, и гнать это в сеть незачем. Правило
%   надёжнее сети, срабатывает мгновенно и не требует обучения.
%
%   Перевыборка точек. Мышь отдаёт точки с постоянным шагом по времени:
%   на медленных участках густо, на быстрых росчерках редко, вплоть до
%   заметных углов. В обучающих же данных точки равномерны по длине, и их
%   от полутора до трёх сотен. Приводим к тому же — иначе сеть получит
%   линию с другой текстурой, чем та, на которой училась.
%
%   Толщина линии и размытие берутся серединами диапазонов из CNCONFIG:
%   на обучении они разыгрывались случайно, здесь разумнее взять типичное.
%
%   См. также CNPREDICT, CNNORMALIZE, CNRASTERIZE, CNRESAMPLEARC.

arguments
    strokes    cell
    canvasSpan (1,1) double {mustBePositive}
end

cfg = cnConfig();

info = struct( ...
    "ok", false, "message", "", "warning", "", ...
    "strokes", {{}}, "tf", [], ...
    "nStrokes", 0, "nDropped", 0, "boxFrac", 0, "thinness", NaN, ...
    "touchesEdge", false);
img = uint8.empty(0,0);

% --- очистка ------------------------------------------------------------
raw = strokes(:);
keep = false(numel(raw),1);
len  = zeros(numel(raw),1);

for i = 1:numel(raw)
    p = raw{i};
    if ~isnumeric(p) || size(p,2) ~= 2
        continue
    end
    p = double(p);
    p = p(all(isfinite(p), 2), :);
    raw{i} = p;

    if size(p,1) < cfg.input.minStrokePoints
        continue
    end
    len(i) = sum(hypot(diff(p(:,1)), diff(p(:,2))));
    keep(i) = len(i) >= cfg.input.minStrokeFrac * canvasSpan;
end

info.nDropped = sum(~keep);
raw = raw(keep);
len = len(keep);

if isempty(raw)
    info.message = "Ничего не нарисовано — или все штрихи слишком короткие.";
    return
end
info.nStrokes = numel(raw);

% --- проверки на вырожденность -----------------------------------------
pts = vertcat(raw{:});
if size(pts,1) < cfg.input.minPoints
    info.message = sprintf("Слишком мало точек (%d). Проведите линию медленнее.", ...
        size(pts,1));
    return
end

lo  = min(pts, [], 1);
hi  = max(pts, [], 1);
ext = max(hi - lo);
info.boxFrac = ext / canvasSpan;

if info.boxFrac < cfg.input.minBoxFrac
    info.message = sprintf( ...
        "Рисунок слишком мелкий (%.0f%% холста). Нарисуйте крупнее.", ...
        100*info.boxFrac);
    return
end

% --- почти прямая линия --------------------------------------------------
% Отрезок не является ни одной из наших кривых, и в датасете его нет даже
% среди каракуль: ломаная там строится минимум из пяти звеньев. Сеть такого
% ввода не видела никогда, а отвечает всё равно уверенно — прямая уходит в
% параболу со стопроцентной уверенностью, потому что парабола ближе прочих.
%
% Мерой служит отношение поперечного размера к продольному в главных осях
% рисунка. Габаритная рамка тут не годится: наклонённый под сорок пять
% градусов отрезок даёт квадратную рамку и выглядит совсем не тонким.
P = pts - mean(pts, 1);
[~, ~, V] = svd(P, 0);
Z = P * V;
e = max(Z, [], 1) - min(Z, [], 1);
info.thinness = min(e) / max(e);

if info.thinness < cfg.input.minThinness
    info.message = "Линия почти прямая — это не кривая.";
    return
end

% --- предупреждение об упирании в край ----------------------------------
% Не ошибка: кривая, упёршаяся в границу, скорее всего обрезана, и это
% исказит форму. Распознаванию не мешаем, но сказать стоит.
half = canvasSpan/2;
tol  = cfg.input.edgeTol * canvasSpan;
if any(abs(pts(:)) > half - tol)
    info.touchesEdge = true;
    info.warning = "Рисунок упирается в край холста — возможно, он обрезан.";
end

% --- приведение к виду обучающих данных ---------------------------------
% Число точек — середина диапазона, на котором училась сеть.
nPts = round(mean(cfg.curve.nPoints));
q = cnResampleArc(raw, nPts);

% Нормализация без остаточного разброса: он нужен только при обучении, как
% регуляризация, а здесь только повредил бы.
[q, tf] = cnNormalize(q);

lw = mean(cfg.img.lineWidth);
sg = mean(cfg.img.softenSigma);
img = cnRasterize(q, lw, sg);

info.ok      = true;
info.strokes = q;
info.tf      = tf;
end
