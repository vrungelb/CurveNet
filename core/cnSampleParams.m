function T = cnSampleParams(key, N, seed)
%CNSAMPLEPARAMS  Розыгрыш параметров для N примеров одного класса.
%
%   T = CNSAMPLEPARAMS(key, N)
%   T = CNSAMPLEPARAMS(key, N, seed)
%
%   Возвращает таблицу из N строк. Одна строка — полный рецепт одного
%   примера: какой формы кривая, под каким углом, насколько испорчена рукой,
%   сколько в ней точек, какой толщины линия. Дальше по этому рецепту
%   CNBUILDDATASET строит картинку уже детерминированно.
%
%   Разделение намеренное: весь случайный выбор сосредоточен здесь, а всё,
%   что ниже, — чистые функции без собственной случайности. Благодаря этому
%   таблица рецептов одновременно служит разметкой для регрессоров и
%   журналом для разбора ошибок классификатора: видно, на каких именно
%   углах, пропорциях и уровнях искажения сеть промахивается.
%
%   Стратификация
%   -------------
%   Непрерывные параметры разыгрываются не независимо, а латинским
%   гиперкубом. Диапазон каждого параметра режется на N равных ячеек, в
%   каждую попадает ровно один пример, а внутри ячейки значение берётся
%   случайно. По каждому параметру в отдельности покрытие получается
%   идеально равномерным — без сгущений и пустот, которые при обычном
%   случайном розыгрыше вполне возможны.
%
%   Ячеек именно N, а не десяток-другой, и это принципиально для второго
%   этапа. Регрессор учится на тех значениях, что видел: если задать ему
%   сетку с шагом 0.2, он научится выдавать только узлы этой сетки и на
%   реальном вводе будет к ним прилипать. При N ячейках значения все разные,
%   и прилипать не к чему.
%
%   Дискретные параметры (число лепестков розы, вид каракули) раздаются
%   поровну и перемешиваются — тот же принцип, но для конечного набора.
%
%   Воспроизводимость
%   -----------------
%   Каждой строке выдаётся собственный seed. Мелкая случайность, которую
%   бессмысленно хранить в таблице — конкретная реализация шума дрожания,
%   места отрывов пера, — разыгрывается ниже по конвейеру из этого seed.
%   Поэтому любой пример восстанавливается точь-в-точь по одной строке
%   таблицы, что незаменимо, когда разбираешься, почему сеть ошиблась
%   именно на нём.
%
%   Столбцы таблицы
%   ---------------
%   idx                 номер примера внутри класса
%   <параметры формы>   имена берутся из поля shape класса
%   k                   число лепестков (только у розы)
%   subtype             вид каракули (только у scribble)
%   angleDeg            угол поворота при генерации, градусы
%   anisoX, anisoY      неравномерное растяжение по осям
%   shear               скос
%   flip                зеркальное отражение по оси X (0/1)
%   warpAmp             амплитуда крупной деформации
%   tremorAmp           амплитуда дрожания
%   radialAmp           амплитуда радиального гуляния
%   openGap             размер незамыкания контура, доля длины; 0 — замкнут
%   nBreaks             число отрывов пера
%   nPoints             сколько точек в кривой
%   lineWidth           толщина линии в пикселях
%   softenSigma         размытие краёв линии
%   scaleJit            остаточный разброс масштаба после нормализации
%   offX, offY          остаточное смещение центра, доли стороны кадра
%   seed                seed этой строки
%
%   См. также CNCLASSES, CNCONFIG, CNCURVEPOINTS, CNBUILDDATASET.

arguments
    key  (1,1) string
    N    (1,1) double {mustBeInteger, mustBePositive}
    seed (1,1) double = NaN
end

cfg = cnConfig();
c   = cnClasses(key);

% Свой seed на класс, выведенный из общего. Так перегенерация одного класса
% не сдвигает розыгрыш у остальных.
if isnan(seed)
    allC = cnClasses();
    ci   = find([allC.key] == key, 1);
    seed = cfg.data.seed + 1000*ci;
end
rs = RandStream("threefry", Seed = seed);

T = table((1:N).', VariableNames = "idx");

% --- параметры формы ---------------------------------------------------
for i = 1:numel(c.shape)
    s = c.shape(i);
    if s.scale == "log"
        % Стратификация ведётся в логарифмической шкале, а обратно значение
        % переводится потенцированием. Так равномерно покрывается не сам
        % параметр, а его порядок — см. пояснение в PAR внутри CNCLASSES.
        T.(s.name) = exp(lhs(rs, N, log(s.lo), log(s.hi)));
    else
        T.(s.name) = lhs(rs, N, s.lo, s.hi);
    end
end

% --- дискретные параметры ----------------------------------------------
if ~isempty(c.kValues)
    T.k = balanced(rs, N, c.kValues(:));
end

if ~c.isCurve
    % Виды каракуль раздаются поровну. Имена должны совпадать с теми, что
    % понимает CNSCRIBBLE.
    T.subtype = balanced(rs, N, ["fourier"; "polyline"; "shape"; "walk"]);
end

% --- поворот ------------------------------------------------------------
% Полный круг: требование — узнавать кривую под любым углом. Стратификация
% здесь особенно важна, потому что угол выкачивает основную долю
% разнообразия датасета, и провал в покрытии сразу виден на живом вводе.
if c.hasAngle
    T.angleDeg = lhs(rs, N, cfg.aug.rotation(1), cfg.aug.rotation(2));
else
    T.angleDeg = zeros(N,1);
end

% --- геометрические искажения -------------------------------------------
% Диапазон растяжения берётся из класса, если он там переопределён: у
% окружности и эллипса общий диапазон перетаскивал бы примеры через границу
% между классами и портил разметку.
an = c.aniso;
if isempty(an)
    an = cfg.aug.aniso;
end
T.anisoX = uni(rs, N, an);
T.anisoY = uni(rs, N, an);
T.shear  = uni(rs, N, cfg.aug.shear);

% --- случайное отражение (зеркалирование) ------------------------------
% Направление закрутки не должно работать признаком класса. Обе спирали
% хиральны: их зеркало не получить никаким поворотом. Если отражать только
% логарифмическую, архимедова остаётся в единственной ориентации, и тогда
% закрутка по часовой стрелке однозначно указывает на логарифмическую —
% архимедовых таких в датасете просто нет. Сеть хватается за этот даровой
% признак вместо честного сравнения шага витков, и логарифмическая спираль
% против часовой стрелки уезжает в archSpiral.
%
% Разыгрывается безусловно, для всех классов. Зеркально-симметричным
% фигурам (окружность, эллипс, парабола, гипербола, астроида, роза,
% кардиоида, улитка) отражение не вредит и распределения не меняет: их
% зеркало совпадает с ними же, повёрнутыми, а поворот и так разыгрывается
% на полном круге. Циклоиде с дробным числом арок и лемнискате с
% асимметрией оно, наоборот, выравнивает покрытие. Список исключений тут
% не заводится намеренно: именно из-за такого списка archSpiral и выпала.
T.flip = randi(rs, [0 1], N, 1);   % 1 — отразить по оси X

% --- имитация руки ------------------------------------------------------
% Обе амплитуды домножены на множитель класса: розе, астроиде и лемнискате
% сильная деформация противопоказана, она съедает саму опознавательную
% геометрию. Стратифицированы, чтобы примеры всех уровней сложности были
% представлены поровну — иначе тяжёлых случаев может случайно оказаться
% мало, и сеть их не выучит.
T.warpAmp   = c.distort * lhs(rs, N, cfg.aug.warpAmp(1),   cfg.aug.warpAmp(2));
T.tremorAmp = c.distort * lhs(rs, N, cfg.aug.tremorAmp(1), cfg.aug.tremorAmp(2));
T.radialAmp = c.distort * lhs(rs, N, cfg.aug.radialAmp(1), cfg.aug.radialAmp(2));

% --- артефакты рисования ------------------------------------------------
% Незамыкание имеет смысл только у замкнутых кривых: у параболы и спирали
% размыкать нечего.
if c.closed
    open = rand(rs, N, 1) < cfg.aug.openProb;
    T.openGap = open .* uni(rs, N, cfg.aug.openGap);
else
    T.openGap = zeros(N,1);
end

brk = rand(rs, N, 1) < cfg.aug.breakProb;
T.nBreaks = brk .* randi(rs, cfg.aug.breakCount, N, 1);

% --- дискретизация и растр ----------------------------------------------
% Число точек с поправкой на плотность: мелко нарисованная кривая
% объективно состоит из меньшего числа точек. Нижняя граница страхует от
% вырожденно редкой линии.
T.nPoints = max(40, round(uni(rs, N, cfg.curve.nPoints) ...
                       .* uni(rs, N, cfg.curve.densityJitter)));

T.lineWidth   = uni(rs, N, cfg.img.lineWidth);
T.softenSigma = uni(rs, N, cfg.img.softenSigma);

% --- остаточный разброс после нормализации ------------------------------
% Идеально вписанные данные делают сеть хрупкой: она привыкает, что кривая
% всегда точно в кадре, и удивляется малейшему отклонению на живом вводе.
T.scaleJit = uni(rs, N, cfg.aug.scaleJitter);
T.offX     = uni(rs, N, cfg.aug.offsetJitter*[-1 1]);
T.offY     = uni(rs, N, cfg.aug.offsetJitter*[-1 1]);

% --- seed строки --------------------------------------------------------
T.seed = randi(rs, [1 2^31-2], N, 1);

T.Properties.Description = sprintf("Рецепты класса %s, seed %d", key, seed);
end


% =======================================================================
function v = lhs(rs, N, lo, hi)
%LHS  Латинский гиперкуб по одному параметру.
%
%   Диапазон делится на N равных ячеек, каждая занимается ровно один раз, а
%   внутри ячейки значение берётся случайно. Порядок ячеек перемешивается,
%   иначе параметр оказался бы связан с номером примера, а через него — со
%   всеми остальными параметрами.

p = randperm(rs, N).';
v = lo + (hi - lo) .* (p - 1 + rand(rs, N, 1)) ./ N;
end


function v = uni(rs, N, range)
%UNI  Равномерное значение из отрезка, без стратификации.

v = range(1) + (range(2) - range(1)) .* rand(rs, N, 1);
end


function v = balanced(rs, N, vals)
%BALANCED  Значения из конечного набора поровну и вперемешку.

reps = ceil(N / numel(vals));
v = repmat(vals, reps, 1);
v = v(1:N);
v = v(randperm(rs, N));
end