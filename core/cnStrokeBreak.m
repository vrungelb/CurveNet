function out = cnStrokeBreak(strokes, rec, closed)
%CNSTROKEBREAK  Незамыкание контура и отрывы пера.
%
%   out = CNSTROKEBREAK(strokes, rec)
%   out = CNSTROKEBREAK(strokes, rec, closed)
%
%   strokes  массив ячеек со штрихами (после CNHANDDISTORT)
%   rec      строка рецепта из CNSAMPLEPARAMS в виде структуры
%   closed   замкнута ли кривая в своей канонической форме
%
%   Возвращает массив ячеек, в котором штрихов может стать больше, чем было:
%   каждый отрыв пера разрезает штрих на два.
%
%   Что моделируется
%   ----------------
%   Незамыкание. Человек не доводит контур до начала — между началом и
%   концом остаётся зазор. Это одно из самых заметных отличий рукописного
%   ввода от идеальной кривой, и без него сеть выучит замкнутость как
%   признак, которого на живом вводе почти не бывает.
%
%   Отрывы пера. Рука отрывается от холста посреди рисунка, линия
%   прерывается и продолжается дальше. У длинных кривых вроде спирали это
%   происходит чаще — там рука объективно устаёт.
%
%   Где именно рвать
%   ----------------
%   Каноническая кривая всегда начинается в одной и той же точке: окружность
%   с нуля градусов, роза с вершины первого лепестка. Если просто отрезать
%   хвост, зазор у всех примеров класса окажется в одном и том же месте
%   относительно формы. Сеть такую регулярность находит мгновенно и начинает
%   различать классы по положению зазора, а не по геометрии — на живом вводе
%   это рассыпается сразу.
%
%   Поэтому перед обрезкой последовательность точек замкнутой кривой
%   циклически сдвигается на случайную величину. Зазор оказывается в
%   случайном месте контура, как и бывает у человека.
%
%   Отрывы не ставятся вплотную к концам штриха: такой отрыв неотличим от
%   недоведённой линии, а этот случай уже описан незамыканием. Огрызки
%   короче порога выбрасываются — на картинке они превращаются в точку или
%   чёрточку, то есть в шум, который сеть может принять за часть формы.
%
%   См. также CNHANDDISTORT, CNSAMPLEPARAMS, CNNORMALIZE, CNRASTERIZE.

arguments
    strokes cell
    rec     (1,1) struct
    closed  (1,1) logical = false
end

need = ["openGap","nBreaks","seed"];
missing = need(~isfield(rec, need));
if ~isempty(missing)
    error("cnStrokeBreak:missingFields", ...
        "В рецепте нет полей: %s.", join(missing, ", "));
end

cfg = cnConfig();
% Отдельный поток, сдвинутый относительно seed строки: иначе отрывы
% оказались бы коррелированы с реализацией шума дрожания, разыгранной из
% того же seed в CNHANDDISTORT.
rs = RandStream("threefry", Seed = mod(rec.seed + 7919, 2^31-1));

strokes = strokes(:);

% --- незамыкание контура ------------------------------------------------
if closed
    for i = 1:numel(strokes)
        strokes{i} = openContour(rs, strokes{i}, rec.openGap);
    end
end

% --- отрывы пера --------------------------------------------------------
out = applyBreaks(rs, strokes, round(rec.nBreaks), cfg);

if isempty(out)
    % Теоретически возможно, если отрывов много, а штрих короткий. Отдаём
    % исходные штрихи: пусть решение о непригодности примера принимает
    % вызывающий код, а не эта функция молча.
    out = strokes;
end
end


% =======================================================================
function p = openContour(rs, p, gap)
%OPENCONTOUR  Циклический сдвиг и снятие хвоста у замкнутого контура.

n = size(p,1);
if n < 8
    return
end

% CNCURVEPOINTS отдаёт замкнутую кривую с совпадающими первой и последней
% точками. Перед циклическим сдвигом дубликат надо снять, иначе он окажется
% посреди линии как пара совпадающих точек.
seg = mean(hypot(diff(p(:,1)), diff(p(:,2))));
if hypot(p(end,1)-p(1,1), p(end,2)-p(1,2)) < 0.5*seg
    p(end,:) = [];
    n = n - 1;
end

p = circshift(p, randi(rs, [0 n-1]), 1);

if gap > 0
    cut = min(max(1, round(gap*n)), n-4);
    p(end-cut+1:end, :) = [];
else
    % Контур остаётся замкнутым, но после сдвига в нём не хватает
    % замыкающего отрезка — возвращаем его явно.
    p(end+1,:) = p(1,:);
end
end


% =======================================================================
function out = applyBreaks(rs, strokes, nBreaks, cfg)
%APPLYBREAKS  Вырезание кусков и разбиение штрихов на фрагменты.

m = numel(strokes);
keep = cell(m,1);
len  = zeros(m,1);
for i = 1:m
    len(i)  = size(strokes{i}, 1);
    keep{i} = true(len(i), 1);
end

for b = 1:nBreaks
    % Штрих выбирается с вероятностью, пропорциональной длине: у длинной
    % кривой рука устаёт сильнее и отрывается чаще.
    i = pickWeighted(rs, len);
    n = len(i);

    margin = max(2, round(cfg.aug.breakMargin * n));
    L = max(2, round(uni(rs, cfg.aug.breakLen) * n));

    lo = margin + 1;
    hi = n - margin - L;
    if hi < lo
        continue    % штрих слишком короткий для отрыва такой длины
    end
    s = randi(rs, [lo hi]);
    keep{i}(s : s+L-1) = false;
end

% Разбиение на непрерывные куски.
out = {};
for i = 1:m
    minFrag = max(4, round(cfg.aug.minFragment * len(i)));
    seg = runsOfTrue(keep{i});
    for j = 1:size(seg,1)
        a = seg(j,1);
        b = seg(j,2);
        if b - a + 1 >= minFrag
            out{end+1,1} = strokes{i}(a:b, :); %#ok<AGROW>
        end
    end
end
end


% =======================================================================
function seg = runsOfTrue(mask)
%RUNSOFTRUE  Границы непрерывных участков истины: матрица [начало конец].

d = diff([0; double(mask(:)); 0]);
seg = [find(d == 1), find(d == -1) - 1];
end


function i = pickWeighted(rs, w)
%PICKWEIGHTED  Индекс, разыгранный с весами, пропорциональными w.

c = cumsum(w(:));
if c(end) <= 0
    i = 1;
    return
end
i = find(rand(rs) * c(end) <= c, 1);
end


function v = uni(rs, range)
%UNI  Одно равномерное значение из отрезка.

v = range(1) + (range(2) - range(1)) * rand(rs);
end
