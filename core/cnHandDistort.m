function out = cnHandDistort(strokes, rec, closed)
%CNHANDDISTORT  Превращение идеальной кривой в рукописную.
%
%   out = CNHANDDISTORT(strokes, rec)
%   out = CNHANDDISTORT(strokes, rec, closed)
%
%   strokes  массив ячеек со штрихами (выход CNCURVEPOINTS)
%   rec      строка рецепта из CNSAMPLEPARAMS, приведённая к структуре:
%            rec = table2struct(T(i,:))
%   closed   замкнута ли кривая; влияет на сшивку деформации по кругу
%
%   Зачем это нужно
%   ---------------
%   Сеть, обученная на идеальных математических кривых, на рукописном вводе
%   разваливается. Причина не в том, что рука рисует «хуже»: свёрточная сеть
%   хватается за самый дешёвый признак, разделяющий классы на обучении. Если
%   все окружности в датасете идеально гладкие, сеть может выучить не
%   «замкнутая линия постоянной кривизны», а буквально «линия без единой
%   шероховатости» — и тогда любая дрожащая рука для неё перестаёт быть
%   окружностью. Поэтому портить надо намеренно и всерьёз.
%
%   Три уровня искажения
%   --------------------
%   1. Аффинное преобразование: неравномерное растяжение, скос, поворот.
%      Растяжение моделирует «эффект угла» — рисуя у края холста, человек
%      подсознательно поджимает фигуру. Само положение на холсте
%      моделировать не нужно, его снимает нормализация.
%
%   2. Крупная упругая деформация: форма плывёт целиком, будто рука ведёт
%      не туда. Реализована как гладкое случайное поле смещений с большой
%      длиной корреляции.
%
%   3. Тремор: мелкое дрожание. Шум обязательно сглаженный — тремор руки
%      коррелирован во времени, а белый шум даёт не дрожащую линию, а ежа.
%
%   Порядок именно такой. Растяжение и скос действуют на саму форму, то есть
%   до поворота; деформация и дрожание возникают уже при ведении руки по
%   холсту, то есть после.
%
%   Амплитуды заданы в долях характерного размера фигуры и домножаются на
%   этот размер здесь. Без такой привязки циклоида, вытянутая по горизонтали
%   на несколько единиц, получила бы относительно ничтожное искажение, а
%   единичная окружность — чрезмерное.
%
%   Штрихи и общая деформация
%   -------------------------
%   Аффинное преобразование одно на всю фигуру: это одна нарисованная вещь,
%   а не набор независимых линий. Крупная деформация складывается из общей
%   части и собственной у каждого штриха — рука ведёт обе ветви гиперболы
%   согласованно, но идеальным зеркалом друг друга они не бывают. Дрожание
%   же полностью независимо: оно происходит на масштабе, где никакой связи
%   между отдельными движениями уже нет.
%
%   У замкнутых кривых поле смещений сшивается по кругу. Иначе в точке, где
%   кривая замыкается, начало и конец получили бы разные смещения, и на
%   картинке появился бы излом, которого в природе нет.
%
%   Отрывы пера и незамыкание контура сюда не входят — это CNSTROKEBREAK.
%
%   См. также CNCURVEPOINTS, CNSAMPLEPARAMS, CNSTROKEBREAK, CNNORMALIZE.

arguments
    strokes cell
    rec     (1,1) struct
    closed  (1,1) logical = false
end

need = ["angleDeg","anisoX","anisoY","shear","warpAmp","tremorAmp","seed"];
% radialAmp, flip намеренно не в списке обязательных: они могут отсутствовать
% в старых рецептах.
missing = need(~isfield(rec, need));
if ~isempty(missing)
    error("cnHandDistort:missingFields", ...
        "В рецепте нет полей: %s.", join(missing, ", "));
end
if isempty(strokes)
    error("cnHandDistort:noStrokes", "Список штрихов пуст.");
end

cfg = cnConfig();
rs  = RandStream("threefry", Seed = rec.seed);

% --- центрирование ------------------------------------------------------
% Аффинное преобразование выполняется относительно центра фигуры, а не
% начала координат. Иначе результат зависел бы от того, где именно лежит
% каноническая кривая: у окружности центр в нуле, а у циклоиды и спирали
% нет, и скос вёл бы себя у них по-разному.
pts = vertcat(strokes{:});
c0  = (max(pts,[],1) + min(pts,[],1)) / 2;
for i = 1:numel(strokes)
    strokes{i} = strokes{i} - c0;
end

% --- уровень 1: аффинное преобразование ---------------------------------
a = deg2rad(rec.angleDeg);
M = [rec.anisoX, rec.shear*rec.anisoY; ...
     0,          rec.anisoY];
R = [cos(a), -sin(a); ...
     sin(a),  cos(a)];
A = R*M;

for i = 1:numel(strokes)
    strokes{i} = strokes{i} * A.';
end

% --- отражение (зеркальное отображение) -------------------------------
% Выполняется после аффинного преобразования, но до деформации: отражение и
% поворот коммутируют с точностью до знака угла, а вот деформация уже нет —
% её след должен ложиться на итоговую форму, а не отражаться вместе с ней.
%
% Нужно оно прежде всего спиралям: закрутка по часовой и против — две
% разные фигуры, и без отражения одна из ориентаций в датасете не
% представлена вовсе. Остальным классам оно безразлично.
%
% Поле flip может отсутствовать в старых рецептах — тогда отражения нет.
if isfield(rec, 'flip') && rec.flip
    for i = 1:numel(strokes)
        strokes{i}(:,1) = -strokes{i}(:,1);   % отражение по оси X
    end
end

% --- характерный размер после преобразования ----------------------------
% Берётся МЕНЬШИЙ габарит, а не больший, и это принципиально. У сильно
% вытянутых фигур опознавательная деталь имеет масштаб короткой стороны, а
% не длинной: у циклоиды из трёх арок ширина около девятнадцати единиц, а
% высота арки — двух. Амплитуда, привязанная к большему габариту, дала бы
% смещение порядка единицы, то есть в полвысоты арки, и арки бы просто
% исчезли — циклоида превращалась в волнистую линию. То же самое губило
% ветви гиперболы и параболы.
%
% Нижняя отсечка нужна для совсем плоских фигур: у почти прямой линии
% меньший габарит близок к нулю, и искажение выродилось бы в ничто.
pts = vertcat(strokes{:});
ext = max(pts,[],1) - min(pts,[],1);
S   = max(min(ext), 0.25*max(ext));
if S <= 0 || ~isfinite(S)
    error("cnHandDistort:degenerate", ...
        "Фигура вырождена: нулевой габарит после преобразования.");
end

% Повторное центрирование: аффинное преобразование линейно и выполняется
% относительно начала координат, поэтому центр габаритной рамки после него
% немного уезжает. Радиальное гуляние ниже отсчитывается от центра фигуры,
% и этот сдвиг надо снять, иначе оно перекосится в одну сторону.
cAff = (max(pts,[],1) + min(pts,[],1)) / 2;
for i = 1:numel(strokes)
    strokes{i} = strokes{i} - cAff;
end

% Поле может отсутствовать в старых рецептах, сгенерированных до появления
% этого вида искажения.
if isfield(rec, "radialAmp")
    radAmp = rec.radialAmp;
else
    radAmp = 0;
end

% --- общая часть деформации --------------------------------------------
% Фигура из нескольких штрихов нарисована одной рукой, и её перекос
% согласован: если рука повела вправо, обе ветви гиперболы уедут вправо
% вместе. При полностью независимой деформации ветви выглядят как две
% несвязанные линии, и класс перестаёт читаться.
%
% Поэтому поле смещений складывается из общей части, одной на всю фигуру, и
% собственной у каждого штриха — идеальным зеркалом друг друга ветви тоже
% не бывают. Веса взяты как w и sqrt(1-w^2), чтобы суммарная дисперсия
% осталась единичной и заданная в рецепте амплитуда не поехала.
multi = numel(strokes) > 1;
if multi
    nMax = max(cellfun(@(p) size(p,1), strokes));
    swS  = max(1, nMax / cfg.aug.warpScale);
    sharedX = smoothNoise(rs, nMax, swS, false);
    sharedY = smoothNoise(rs, nMax, swS, false);
    uShared = linspace(0, 1, nMax).';
end
w = cfg.aug.warpShare;

% --- уровни 2 и 3: деформация и дрожание --------------------------------
out = strokes;
for i = 1:numel(strokes)
    p = strokes{i};
    n = size(p,1);
    if n < 4
        continue    % деформировать нечего
    end

    % Длина корреляции крупной деформации задана долей длины штриха: она
    % должна плыть на масштабе всей фигуры, а не отдельных её кусков.
    wrap = closed && ~multi;
    sw   = max(1, n / cfg.aug.warpScale);

    wx = smoothNoise(rs, n, sw, wrap);
    wy = smoothNoise(rs, n, sw, wrap);
    if multi
        u  = linspace(0, 1, n).';
        wx = w*interp1(uShared, sharedX, u) + sqrt(1-w^2)*wx;
        wy = w*interp1(uShared, sharedY, u) + sqrt(1-w^2)*wy;
    end

    p = p + rec.warpAmp * S * [wx, wy];

    % Тремор — та же конструкция, но с короткой длиной корреляции. Она
    % задана в точках, а не в долях, потому что дрожание руки не зависит от
    % того, какой длины линию человек рисует.
    p = p + rec.tremorAmp * S * ...
        [smoothNoise(rs, n, cfg.aug.tremorSigma, wrap), ...
         smoothNoise(rs, n, cfg.aug.tremorSigma, wrap)];

    % Радиальное гуляние: рука не держит постоянного расстояния от центра
    % фигуры. Множитель, а не сдвиг — отклонение растёт вместе с радиусом,
    % как оно и бывает у человека, а центр фигуры остаётся на месте.
    %
    % Для спиралей это главный вид искажения: именно он заставляет шаг
    % витков гулять. Без него все архимедовы спирали в датасете имеют
    % идеально постоянный шаг, которого от руки не бывает, и живая спираль
    % с расходящимися витками уходит в логарифмические.
    if radAmp > 0
        p = p .* (1 + radAmp * smoothNoise(rs, n, sw, wrap));
    end

    out{i} = p;
end
end


% =======================================================================
function v = smoothNoise(rs, n, sigma, wrap)
%SMOOTHNOISE  Гладкий случайный сигнал единичной дисперсии.
%
%   Белый шум, свёрнутый с гауссовым ядром. Именно сглаженный, а не белый:
%   дрожание руки коррелировано во времени, соседние точки смещаются
%   согласованно. Белый шум дал бы иглы, а не дрожащую линию.
%
%   При wrap = true свёртка круговая, и сигнал стыкуется сам с собой: это
%   нужно замкнутым кривым, иначе в точке замыкания возникает излом.

sigma = max(sigma, 0.5);
pad   = min(n-1, ceil(3*sigma));

x = randn(rs, n, 1);

k = exp(-(-pad:pad).^2 / (2*sigma^2)).';
k = k / sum(k);

% Индексы окна вокруг каждой точки: по кругу для замкнутых кривых, с
% повтором крайних значений для разомкнутых.
idx = (1:n).' + (-pad:pad);
if wrap
    idx = mod(idx - 1, n) + 1;
else
    idx = min(max(idx, 1), n);
end

v = x(idx) * k;

% Сглаживание сильно снижает дисперсию, причём тем сильнее, чем шире ядро.
% Без нормировки амплитуда искажения зависела бы от длины корреляции, а не
% от заданного в рецепте значения.
s = std(v);
if s > 0
    v = v / s;
end
end