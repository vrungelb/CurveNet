function strokes = cnCurvePoints(key, prm, n)
%CNCURVEPOINTS  Точки идеальной кривой в канонической форме.
%
%   strokes = CNCURVEPOINTS(key, prm)      256 точек по умолчанию
%   strokes = CNCURVEPOINTS(key, prm, n)   ровно n точек на всю кривую
%
%   key    ключ класса из CNCLASSES
%   prm    структура с параметрами формы; имена полей совпадают с именами
%          из поля shape соответствующего класса, плюс поле k у розы
%   n      суммарное число точек по всем штрихам
%
%   Возвращает массив ячеек, в каждой ячейке — один штрих размера M x 2.
%   Ячейка всегда одна, кроме гиперболы: две её ветви физически нельзя
%   провести не отрывая руки, поэтому это два отдельных штриха. Массив
%   ячеек возвращается даже для одного штриха, чтобы у вызывающего кода не
%   было двух разных веток обработки.
%
%   Каноническая форма
%   ------------------
%   Этот файл — единственное место, где записано, что считается эталоном
%   каждой кривой. Все кривые строятся в собственной канонической позиции:
%   центр симметрии или характерная точка в начале координат, характерный
%   размер порядка единицы, нулевой поворот. Положение, масштаб и угол
%   добавляются позже аугментацией и снимаются нормализацией, поэтому
%   абсолютный масштаб здесь роли не играет — важна только форма.
%
%   CNEQUATION обязан использовать те же самые формулы, иначе уравнение,
%   показанное пользователю, не будет соответствовать наложенной кривой.
%   Меняя что-то здесь, проверьте и там.
%
%   Точки равномерны по длине дуги, а не по параметру. Кривая сначала
%   считается по густой сетке параметра, а затем прореживается через
%   CNRESAMPLEARC. Без этого у спирали витки у центра шли бы густо, а на
%   периферии редко, а у розы точки скапливались бы в основаниях лепестков.
%
%   Замкнутые кривые возвращаются замкнутыми: последняя точка совпадает с
%   первой. Незамыкание — это артефакт живого рисования, и его добавляет
%   CNSTROKEBREAK, а не эта функция.
%
%   См. также CNCLASSES, CNRESAMPLEARC, CNSAMPLEPARAMS, CNEQUATION.

arguments
    key (1,1) string
    prm (1,1) struct
    n   (1,1) double {mustBeInteger, mustBePositive} = 256
end

c = cnClasses(key);
if ~c.isCurve
    error("cnCurvePoints:notACurve", ...
        "Класс «%s» не является кривой; каракули строит cnScribble.", key);
end
checkParams(c, prm);

% Густота предварительной сетки. Берётся с большим запасом относительно n:
% по ней считается длина дуги, и от её точности зависит равномерность
% итогового прореживания.
nd = max(4000, 12*n);

switch key

    % --- окружность ---------------------------------------------------
    % Единичная окружность с центром в начале координат. Формы у неё нет:
    % после нормализации она полностью определяется габаритной рамкой.
    case "circle"
        t = linspace(0, 2*pi, nd).';
        raw = {[cos(t), sin(t)]};

    % --- эллипс -------------------------------------------------------
    % Большая полуось равна единице и лежит вдоль оси x, малая равна 1/elong.
    % Параметром служит вытянутость a/b, а не обратное отношение: так число
    % растёт вместе с тем, что видно на картинке, и его удобнее и задавать,
    % и читать в предсказании регрессора.
    case "ellipse"
        t = linspace(0, 2*pi, nd).';
        raw = {[cos(t), sin(t)/prm.elong]};

    % --- парабола -----------------------------------------------------
    % Каноническая форма y = x^2/2, то есть фокальный параметр равен
    % единице; ветви идут вверх. halfLength — это половина длины отрезка по
    % x, на котором кривая нарисована. После равномерного вписывания в кадр
    % именно она задаёт пропорцию ветвей, а настоящий фокальный параметр
    % восстанавливается из неё и размера габаритной рамки.
    case "parabola"
        x = linspace(-prm.halfLength, prm.halfLength, nd).';
        raw = {[x, 0.5*x.^2]};

    % --- гипербола ----------------------------------------------------
    % Каноническая форма x^2 - y^2/b^2 = 1, действительная полуось равна
    % единице и лежит вдоль оси x. Ветви параметризованы гиперболическими
    % функциями: x = ±ch(u), y = b*sh(u). Параметр uMax задаёт, насколько
    % далеко человек увёл ветви от вершин.
    % Две ветви — два штриха. Правая идёт первой, потому что правша обычно
    % начинает с неё, но для растра порядок безразличен.
    case "hyperbola"
        u  = linspace(-prm.uMax, prm.uMax, nd).';
        ch = cosh(u);
        sh = prm.b*sinh(u);
        raw = {[ch, sh], [-ch, sh]};

    % --- спираль Архимеда ---------------------------------------------
    % r = theta, то есть шаг витков постоянен. Начинается ровно в центре,
    % как её и рисует человек. Коэффициент пропорциональности опущен: он
    % задаёт только масштаб, который снимается нормализацией.
    case "archSpiral"
        th  = linspace(0, 2*pi*prm.turns, nd).';
        raw = {[th.*cos(th), th.*sin(th)]};

    % --- логарифмическая спираль --------------------------------------
    % r = exp(growth*theta): шаг витков растёт в геометрической прогрессии,
    % и этим она отличается от архимедовой. Центра такая спираль формально
    % не достигает никогда, витки лишь бесконечно к нему приближаются —
    % внутренние оказываются мельче пикселя и на картинке пропадают. Это не
    % дефект: человек их тоже не нарисует.
    case "logSpiral"
        th  = linspace(0, 2*pi*prm.turns, nd).';
        r   = exp(prm.growth*th);
        raw = {[r.*cos(th), r.*sin(th)]};

    % --- роза Гранди --------------------------------------------------
    % r = cos(k*theta). При нечётном k полный обход даёт k лепестков за
    % половину оборота, при чётном — 2k лепестков за полный оборот. Радиус
    % принимает отрицательные значения, и это нормально: точка при этом
    % откладывается в противоположную сторону, из чего и складываются
    % лепестки.
    case "rose"
        k = prm.k;
        if mod(k,2) == 1
            th = linspace(0, pi, nd).';
        else
            th = linspace(0, 2*pi, nd).';
        end
        r   = cos(k*th);
        raw = {[r.*cos(th), r.*sin(th)]};

    % --- лемниската Бернулли ------------------------------------------
    % Используется рациональная параметризация, а не полярная r^2=cos(2t):
    % полярная задаёт две дольки отдельными кусками и требует сшивки, а эта
    % обходит всю восьмёрку одним непрерывным движением — ровно так, как её
    % рисует рука. Своей формы у лемнискаты нет, все лемнискаты подобны.
    case "lemniscate"
        t   = linspace(0, 2*pi, nd).';
        d   = 1 + sin(t).^2;
        raw = {[cos(t)./d, sin(t).*cos(t)./d]};

    % --- циклоида -----------------------------------------------------
    % След точки окружности единичного радиуса, катящейся по оси x:
    % x = t - sin(t), y = 1 - cos(t). Параметр arches — число арок, дробные
    % значения допустимы, человек вполне может оборвать рисунок на середине
    % арки.
    case "cycloid"
        t   = linspace(0, 2*pi*prm.arches, nd).';
        raw = {[t - sin(t), 1 - cos(t)]};

    % --- астроида -----------------------------------------------------
    % x = cos^3(t), y = sin^3(t). Четыре острия смотрят вдоль осей; именно
    % они и являются опознавательным признаком класса.
    case "astroid"
        t   = linspace(0, 2*pi, nd).';
        raw = {[cos(t).^3, sin(t).^3]};

    % --- кардиоида ----------------------------------------------------
    % r = 1 - cos(theta): остриё лежит в начале координат, выпуклость
    % направлена вправо. Это частный случай улитки Паскаля при b = a, и
    % именно поэтому у улитки в CNCLASSES запрещена окрестность единицы.
    case "cardioid"
        th  = linspace(0, 2*pi, nd).';
        r   = 1 - cos(th);
        raw = {[r.*cos(th), r.*sin(th)]};

    % --- улитка Паскаля -----------------------------------------------
    % r = 1 + ratio*cos(theta), где ratio = b/a. При ratio больше единицы
    % радиус меняет знак и возникает внутренняя петля — единственное, что
    % надёжно отличает улитку от кардиоиды на картинке.
    case "limacon"
        th  = linspace(0, 2*pi, nd).';
        r   = 1 + prm.ratio*cos(th);
        raw = {[r.*cos(th), r.*sin(th)]};

    otherwise
        error("cnCurvePoints:unhandled", ...
            "Для класса «%s» не задана формула.", key);
end

if numel(raw) ~= c.nStrokes
    error("cnCurvePoints:strokeMismatch", ...
        "Класс «%s» описан как %d штриха(ов), а построено %d.", ...
        key, c.nStrokes, numel(raw));
end

strokes = cnResampleArc(raw, n);
end


% =======================================================================
function checkParams(c, prm)
%CHECKPARAMS  Проверка, что переданы все параметры, требуемые классом.

need = strings(0,1);
if ~isempty(c.shape)
    need = [c.shape.name].';
end
if ~isempty(c.kValues)
    need(end+1) = "k";
end

missing = need(~isfield(prm, need));
if ~isempty(missing)
    error("cnCurvePoints:missingParams", ...
        "Для класса «%s» не заданы параметры: %s.", c.key, join(missing, ", "));
end

for i = 1:numel(need)
    v = prm.(need(i));
    if ~isnumeric(v) || ~isscalar(v) || ~isfinite(v)
        error("cnCurvePoints:badParam", ...
            "Параметр «%s» класса «%s» должен быть конечным числом.", ...
            need(i), c.key);
    end
end

% Число лепестков обязано быть целым: дробное k даёт незамкнутую кривую,
% которая розой уже не является.
if ~isempty(c.kValues)
    if mod(prm.k,1) ~= 0 || prm.k < 2
        error("cnCurvePoints:badK", ...
            "Число лепестков должно быть целым не меньше двух, получено %g.", prm.k);
    end
end
end
