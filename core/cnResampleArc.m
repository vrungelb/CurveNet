function [out, L] = cnResampleArc(pts, n, method)
%CNRESAMPLEARC  Пересчёт точек кривой на равномерные по длине дуги.
%
%   q = CNRESAMPLEARC(p, n)            один штрих: p размера M x 2 -> q размера n x 2
%   q = CNRESAMPLEARC(c, n)            несколько штрихов: c — массив ячеек
%   q = CNRESAMPLEARC(..., method)     способ интерполяции, по умолчанию "pchip"
%   [q, L] = CNRESAMPLEARC(...)        дополнительно полная длина ломаной
%
%   Зачем это нужно
%   ---------------
%   Кривая, посчитанная по равномерной сетке своего параметра, имеет крайне
%   неравномерную плотность точек. У спирали витки у центра идут густо, а на
%   периферии редко; у розы точки скапливаются в основании лепестков. При
%   растеризации это даёт рваную линию в одних местах и слипшуюся в других,
%   а при имитации дрожания руки — неравномерную амплитуду шума, потому что
%   шум задаётся на точку, а не на единицу длины.
%
%   Ровно та же задача возникает на живом вводе, но с другой стороны: мышь
%   отдаёт точки с постоянным шагом по времени, значит на медленных участках
%   густо, а на быстрых росчерках редко, вплоть до заметных углов.
%
%   Поэтому и синтетика, и рисунок пользователя проходят через эту функцию.
%   Препроцессинг обязан быть общим — иначе сеть обучится на одном
%   распределении точек, а работать будет на другом.
%
%   Несколько штрихов
%   -----------------
%   Если на входе массив ячеек, n распределяется между штрихами
%   пропорционально их длине, но не меньше двух точек на штрих. Именно
%   пропорционально длине, а не поровну: у гиперболы ветви обычно разной
%   длины, и поровну означало бы разную плотность линии на одной картинке.
%
%   Интерполяция
%   ------------
%   По умолчанию "pchip" — она сохраняет форму и не даёт выбросов между
%   узлами, в отличие от обычного сплайна, который на редких точках любит
%   вылезать петлями. Для плотного входа разница с "linear" незаметна, а на
%   разреженном вводе с мыши она принципиальна: линейная интерполяция
%   оставит видимые изломы.
%
%   Совпадающие подряд точки (мышь стоит на месте) отбрасываются: они дают
%   нулевые отрезки, а по ним нельзя строить монотонную координату длины.
%
%   См. также CNCURVEPOINTS, CNNORMALIZE, CNRASTERIZE.

arguments
    pts
    n      (1,1) double {mustBeInteger, mustBePositive}
    method (1,1) string = "pchip"
end

if iscell(pts)
    [out, L] = resampleMany(pts, n, method);
else
    [out, L] = resampleOne(pts, n, method);
end
end


% =======================================================================
function [q, L] = resampleOne(p, n, method)

p = validateStroke(p);
[p, s, L] = arcLength(p);

if size(p,1) < 2
    % Штрих схлопнулся в точку. Возвращаем её же нужное число раз: пусть
    % решение о том, что такой ввод бессмысленен, принимает вызывающий код
    % по своим порогам, а не эта функция молча.
    q = repmat(p(1,:), n, 1);
    return
end

st = linspace(0, L, n).';
q  = [interp1(s, p(:,1), st, method), ...
      interp1(s, p(:,2), st, method)];
end


% =======================================================================
function [q, L] = resampleMany(c, n, method)

c = c(:);
m = numel(c);
if m == 0
    error("cnResampleArc:noStrokes", "Список штрихов пуст.");
end

len = zeros(m,1);
for i = 1:m
    c{i} = validateStroke(c{i});
    [~, ~, len(i)] = arcLength(c{i});
end
L = sum(len);

% Распределение точек по штрихам пропорционально длине.
if L > 0
    cnt = max(2, round(n * len / L));
else
    cnt = repmat(max(2, floor(n/m)), m, 1);
end

% Округление вверх по каждому штриху даёт перебор, а нижняя граница в две
% точки — недобор на очень коротких штрихах. Разницу снимаем с самого
% длинного штриха: на нём одна точка туда-сюда ничего не меняет.
d = n - sum(cnt);
if d ~= 0
    [~, big] = max(len);
    cnt(big) = max(2, cnt(big) + d);
end

q = cell(m,1);
for i = 1:m
    q{i} = resampleOne(c{i}, cnt(i), method);
end
end


% =======================================================================
function p = validateStroke(p)

if ~isnumeric(p) || ~ismatrix(p) || size(p,2) ~= 2
    error("cnResampleArc:badShape", ...
        "Штрих должен быть числовой матрицей размера M x 2.");
end
p = double(p);

% Строки с NaN и Inf выбрасываем: они появляются как разделители штрихов и
% как результат вычисления кривой в особых точках.
p = p(all(isfinite(p), 2), :);

if isempty(p)
    error("cnResampleArc:emptyStroke", ...
        "После удаления NaN в штрихе не осталось точек.");
end
end


% =======================================================================
function [p, s, L] = arcLength(p)
%ARCLENGTH  Кумулятивная длина вдоль ломаной со снятием повторов.
%
%   interp1 требует строго возрастающих узлов, поэтому точки, не
%   продвигающие длину, надо убрать. Проверять сами длины отрезков на
%   положительность недостаточно: отрезок может быть ненулевым, но
%   настолько коротким по сравнению с уже накопленной длиной, что при
%   сложении он в double просто теряется, и накопленная длина не меняется.
%   Именно так и происходит на ломаных со сближенными вершинами.
%
%   Поэтому условие ставится не на длину отрезка, а прямо на приращение
%   накопленной суммы — то есть на ту величину, которая и пойдёт в interp1.
%   Так строгое возрастание гарантировано по построению.

d = [0; hypot(diff(p(:,1)), diff(p(:,2)))];
s = cumsum(d);

keep = [true; diff(s) > 0];
p = p(keep, :);
s = s(keep);

L = s(end);
end
