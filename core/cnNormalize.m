function [q, tf] = cnNormalize(strokes, jitter)
%CNNORMALIZE  Приведение штрихов к единому кадру.
%
%   q       = CNNORMALIZE(strokes)
%   [q, tf] = CNNORMALIZE(strokes)
%   [q, tf] = CNNORMALIZE(strokes, jitter)
%
%   strokes  массив ячеек со штрихами в произвольных координатах
%   jitter   необязательная структура с полями scaleJit, offX, offY —
%            остаточный разброс, применяемый только при генерации датасета
%
%   q   штрихи в нормализованном кадре: единичный квадрат, начало в левом
%       нижнем углу; фигура вписана по центру с полем cfg.img.pad
%   tf  преобразование, связывающее кадр с исходными координатами:
%       p = (q - 0.5 - tf.offset) * tf.scale + tf.center
%
%   Что здесь происходит и зачем
%   ----------------------------
%   Тип кривой не зависит от того, где на холсте она нарисована и какого
%   размера: парабола остаётся параболой в любом углу и при любом масштабе.
%   Значит эту информацию можно и нужно выбросить до того, как картинка
%   попадёт в сеть — тогда сети не придётся тратить ёмкость на выучивание
%   того, что и так известно точно.
%
%   Считается общая габаритная рамка по всем штрихам сразу, а не по каждому
%   отдельно. Иначе две ветви гиперболы разъехались бы или наложились друг
%   на друга.
%
%   Масштабирование строго равномерное, одним коэффициентом по обеим осям.
%   Соблазн растянуть фигуру так, чтобы она заполнила кадр целиком, велик,
%   но это уничтожает пропорции: любой эллипс превратился бы в окружность, а
%   парабола потеряла бы единственный параметр, отличающий одну от другой.
%   Именно сохранённая пропорция позволяет потом восстановить фокальный
%   параметр и отношение полуосей.
%
%   Поле по краям нужно по двум причинам: линия конечной толщины не должна
%   упираться в границу кадра, и небольшой запас делает сеть устойчивее к
%   неточностям вписывания на живом вводе.
%
%   Положение и размер не теряются, а уходят в tf. При генерации датасета
%   это преобразование не нужно, но на живом вводе именно оно позволит
%   вернуть уравнение в координатах холста, а не в кадре сети.
%
%   Одна функция на синтетику и на живой ввод
%   -----------------------------------------
%   Эта функция ничего не знает о классах и работает с любыми точками.
%   Благодаря этому и сгенерированная кривая, и рисунок пользователя
%   проходят через один и тот же код. Расхождение здесь было бы худшим из
%   возможных: сеть обучилась бы на одном представлении, а работала на
%   другом, причём отличие было бы незаметным глазу.
%
%   Поворот здесь не снимается и сниматься не может. Есть соблазн выровнять
%   фигуру по главным осям, но у окружности, розы и астроиды выделенного
%   направления нет, и главная ось определялась бы шумом, прыгая от запуска
%   к запуску. Поворот закрывается аугментацией, а не нормализацией.
%
%   См. также CNRASTERIZE, CNSTROKEBREAK, CNCURVEPOINTS.

arguments
    strokes cell
    jitter        = []
end

if isempty(strokes)
    error("cnNormalize:noStrokes", "Список штрихов пуст.");
end

cfg = cnConfig();

% --- общая габаритная рамка --------------------------------------------
pts = vertcat(strokes{:});
pts = pts(all(isfinite(pts), 2), :);
if size(pts,1) < 2
    error("cnNormalize:tooFewPoints", ...
        "Для нормализации нужно хотя бы две конечные точки.");
end

lo = min(pts, [], 1);
hi = max(pts, [], 1);
c0 = (lo + hi) / 2;

% Делим на максимум из ширины и высоты, а не по каждой оси отдельно. Это и
% есть равномерность, и она же страхует от вырождения: у почти прямой линии
% высота рамки близка к нулю, и деление по осям дало бы бесконечность.
ext = max(hi - lo);
if ~isfinite(ext) || ext <= 0
    error("cnNormalize:degenerate", ...
        "Габаритная рамка вырождена: фигура схлопнулась в точку.");
end

fill  = 1 - 2*cfg.img.pad;      % какую долю кадра занимает фигура
scale = ext / fill;             % единиц исходных координат на единицу кадра

% --- перенос в кадр -----------------------------------------------------
q = strokes(:);
for i = 1:numel(q)
    q{i} = (q{i} - c0) / scale + 0.5;
end

% --- остаточный разброс -------------------------------------------------
% Только для генерации датасета. Идеально вписанные данные делают сеть
% хрупкой: она привыкает, что фигура всегда занимает кадр ровно, и
% удивляется малейшему отклонению на живом вводе, где рамка считается по
% дрожащей линии и всегда немного врёт.
sj = 1;
off = [0 0];
if ~isempty(jitter)
    if isfield(jitter, "scaleJit"); sj = jitter.scaleJit; end
    if isfield(jitter, "offX") && isfield(jitter, "offY")
        off = [jitter.offX, jitter.offY];
    end
    for i = 1:numel(q)
        q{i} = (q{i} - 0.5) * sj + 0.5 + off;
    end
end

% --- описание преобразования -------------------------------------------
tf = struct( ...
    "center",   c0, ...          % центр габаритной рамки в исходных координатах
    "extent",   ext, ...         % больший габарит в исходных координатах
    "pad",      cfg.img.pad, ...
    "scale",    scale / sj, ...  % p = (q - 0.5 - offset)*scale + center
    "offset",   off, ...
    "boxMin",   lo, ...
    "boxMax",   hi);
end
