function img = cnRasterize(strokes, lineWidth, softenSigma)
%CNRASTERIZE  Отрисовка штрихов в квадратную матрицу изображения.
%
%   img = CNRASTERIZE(strokes)
%   img = CNRASTERIZE(strokes, lineWidth)
%   img = CNRASTERIZE(strokes, lineWidth, softenSigma)
%
%   strokes      массив ячеек со штрихами в нормализованном кадре, то есть
%                в единичном квадрате (выход CNNORMALIZE)
%   lineWidth    толщина линии в пикселях
%   softenSigma  размытие краёв линии в пикселях
%
%   Возвращает изображение uint8 размера cfg.img.size на cfg.img.size:
%   белая линия на чёрном фоне.
%
%   Почему не figure и print
%   ------------------------
%   Отрисовка через график с последующим снятием картинки занимает порядка
%   пятидесяти миллисекунд на кадр. На девяноста тысячах примеров это
%   полтора часа только на растеризацию, и это при том, что сама работа —
%   заполнение матрицы 160 на 160. Прямая растеризация укладывается в единицы
%   миллисекунд, и весь датасет собирается за несколько минут.
%
%   Как считается линия
%   -------------------
%   Штрих уплотняется до шага заметно меньше пикселя и отмечается в
%   булевой маске — это осевая линия нулевой толщины. Затем по маске
%   считается карта расстояний: для каждого пикселя кадра — расстояние до
%   ближайшей точки осевой линии. Толстая линия получается как множество
%   точек, отстоящих от оси не дальше половины толщины, а плавный край
%   возникает сам собой из дробной части расстояния.
%
%   Такой способ даёт ровно заданную толщину независимо от кривизны и не
%   утолщает линию в местах, где она идёт под углом к сетке пикселей.
%
%   Уплотнение обязательно: если оставить исходные полторы-три сотни точек,
%   на участках с большой кривизной соседние точки окажутся в нескольких
%   пикселях друг от друга и линия распадётся на пунктир.
%
%   Штрихи не соединяются
%   ---------------------
%   Каждый штрих обрабатывается отдельно, конец одного никогда не
%   соединяется с началом следующего. Это главная ловушка задачи: если
%   сложить все точки в один массив и провести по ним линию, через разрыв
%   между ветвями гиперболы протянется отрезок, которого человек не рисовал.
%
%   Белое на чёрном
%   ---------------
%   Фон равен нулю, и это совпадает с тем, чем свёрточные слои дополняют
%   края при паддинге. При обратной раскраске сеть видела бы на границе
%   кадра ложную линию из нулей на белом фоне.
%
%   См. также CNNORMALIZE, CNRESAMPLEARC, CNBUILDDATASET.

arguments
    strokes     cell
    lineWidth   (1,1) double {mustBePositive} = 2.2
    softenSigma (1,1) double {mustBeNonnegative} = 0.6
end

cfg = cnConfig();
N   = cfg.img.size;

img = zeros(N, N, "single");
if isempty(strokes)
    img = toUint8(img, cfg);
    return
end

% --- осевая линия в маске ----------------------------------------------
mask = false(N, N);
drawn = false;

for i = 1:numel(strokes)
    p = strokes{i};
    p = p(all(isfinite(p), 2), :);
    if size(p,1) < 2
        continue
    end

    % Перевод в пиксельные координаты. Ось y переворачивается: в кадре она
    % направлена вверх, а строки изображения нумеруются сверху вниз.
    cx = p(:,1) * (N-1) + 1;
    cy = (1 - p(:,2)) * (N-1) + 1;

    % Уплотнение до шага меньше пикселя. Число точек считается по реальной
    % длине штриха в пикселях, поэтому короткие штрихи не получают лишних
    % точек, а длинные не остаются разреженными.
    L  = sum(hypot(diff(cx), diff(cy)));
    nd = max(2, ceil(L / cfg.img.splatStep));
    d  = cnResampleArc([cx, cy], nd, "linear");

    % Округление до ближайшего пикселя. Точки, вышедшие за кадр,
    % отбрасываются, а не прижимаются к границе: прижатые собрались бы в
    % полосу вдоль края, которой в рисунке не было.
    xi = round(d(:,1));
    yi = round(d(:,2));
    ok = xi >= 1 & xi <= N & yi >= 1 & yi <= N;
    if ~any(ok)
        continue
    end

    mask(sub2ind([N N], yi(ok), xi(ok))) = true;
    drawn = true;
end

if ~drawn
    img = toUint8(img, cfg);
    return
end

% --- толщина через карту расстояний ------------------------------------
% D(i,j) — расстояние от пикселя до ближайшей точки осевой линии.
D = single(bwdist(mask));

% Половина толщины плюс полпикселя: слагаемое даёт плавный край шириной
% ровно в один пиксель, то есть обычное сглаживание, а не ступеньку.
img = min(1, max(0, lineWidth/2 - D + 0.5));

% --- размытие краёв -----------------------------------------------------
% Холст рисует с антиалиасингом, и синтетика должна выглядеть так же. Если
% этого не сделать, сеть научится отличать «идеально резкий край» от
% «размытого» и провалится на живом вводе.
if softenSigma > 0
    img = blurSeparable(img, softenSigma);
    m = max(img(:));
    if m > 0
        img = img / m;    % размытие сажает яркость линии, возвращаем её
    end
end

img = toUint8(img, cfg);
end


% =======================================================================
function img = blurSeparable(img, sigma)
%BLURSEPARABLE  Гауссово размытие двумя одномерными свёртками.
%
%   Разделение на две одномерные свёртки вместо одной двумерной: результат
%   тот же, а работы на порядок меньше.

r = max(1, ceil(3*sigma));
k = exp(-(-r:r).^2 / (2*sigma^2));
k = single(k / sum(k));

img = conv2(k.', k, img, "same");
end


% =======================================================================
function img = toUint8(img, cfg)
%TOUINT8  Перевод в целочисленное изображение с учётом раскраски.

if ~cfg.img.lineOnBlack
    img = 1 - img;
end
img = uint8(round(255 * min(1, max(0, img))));
end
